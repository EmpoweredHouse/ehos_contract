defmodule EhOsContract.Docs do
  @moduledoc """
  The manifest of the package's documentation (#141): which pages are generated, from
  what, and where they go. `mix eh_os_contract.docs` writes them from here and
  `--check` holds them to the code.

  It lives in `dev/` and is not shipped: it describes this package's pages, not a
  host's.
  """

  alias EhOsContract.Docs.{DslPages, ModulePages}

  @marker "<!-- Generated by `mix eh_os_contract.docs`"

  @typedoc "A generated page: where it goes and its Markdown."
  @type page() :: {path :: String.t(), markdown :: String.t()}

  @doc """
  The pages written by hand: they may say what they cover and hold generated regions
  (`EhOsContract.Docs.Prose`). Every page ExDoc builds is generated (here, or
  `docs/rules.md` by `eh_os_contract.rules`), listed here, or the changelog, which
  `test/docs_test.exs` holds.
  """
  @spec prose() :: [String.t()]
  def prose do
    ["README.md", "docs/introduction.md", "docs/getting-started.md", "docs/contract.md"] ++
      Enum.map(concepts(), &"docs/concepts/#{&1}.md") ++
      ["docs/authorization.md", "docs/glossary.md"]
  end

  @doc "The concept pages, in the order a reader takes them."
  @spec concepts() :: [String.t()]
  def concepts do
    ~w(domain domain-data units reactions reading forms between-contracts process scenarios)
  end

  # Each DSL with the prefix of its reference pages.
  @dsls [
    domain: EhOsContract.Domain.Dsl,
    contract: EhOsContract.Contract.Dsl,
    process: EhOsContract.Process.Dsl
  ]

  @doc "The DSLs whose reference is generated and whose entities a prose page may cover."
  @spec extensions() :: [module()]
  def extensions, do: Keyword.values(@dsls)

  @doc "Every generated page, in the order it is written."
  @spec generated() :: [page()]
  def generated do
    Enum.flat_map(@dsls, fn {name, dsl} ->
      DslPages.pages(dsl, "docs/dsl/#{name}-dsl.md", "#{name}")
    end) ++
      [
        {"docs/configuration.md", configuration()},
        {"docs/cli.md", ModulePages.cli()},
        {"docs/behaviours.md", ModulePages.behaviours()}
      ]
  end

  @doc """
  The marker line every generated page starts with, so a page the manifest no longer
  lists can be told from one written by hand before it is deleted.
  """
  @spec marker?(String.t()) :: boolean()
  def marker?(markdown), do: String.starts_with?(markdown, @marker)

  @doc "The marker line of a page generated from `source`."
  @spec marker(String.t()) :: String.t()
  def marker(source), do: "#{@marker} from #{source}. Do not edit. -->"

  @doc """
  `text` with its own headings `levels` below where they were: with 2, `#` becomes
  `###`. Code blocks are left as they are.
  """
  @spec shift(String.t(), pos_integer()) :: String.t()
  def shift(text, levels \\ 2) do
    deeper = String.duplicate("#", levels)

    text
    |> String.trim()
    |> String.split(~r/(```.*?```)/su, include_captures: true)
    |> Enum.map_join(fn
      "```" <> _ = code -> code
      prose -> Regex.replace(~r/^(#+)/mu, prose, deeper <> "\\1")
    end)
  end

  defp configuration do
    """
    #{marker("EhOsContract.Config")}

    # Configuration

    Every key of `config :eh_os_contract`. The engine checks them when it starts: an
    unknown key, a value of the wrong shape or a missing required key stops it, with a
    message naming the key.

        config :eh_os_contract,
          applications: [:my_app],
          repo: MyApp.Repo

    #{EhOsContract.Config.docs()}\
    """
  end
end
