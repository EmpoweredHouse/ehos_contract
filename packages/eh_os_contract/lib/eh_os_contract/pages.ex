    |> Enum.reject(&is_nil/1)
  end

  defp invariants(_site, []), do: []

  # The owner reads each rule in its words; its examples are the code's tests.
  defp invariants(%{audience: :owner}, invariants) do
    ["", "## Rules", "" | for(i <- invariants, do: "- #{i.label}#{source_note(i)}")]
  end

  defp invariants(_site, invariants) do
    [
      "",
      "## Invariants",
      "",
      "Dispatch holds every value of the type to each, and every example is a test.",
      for i <- invariants do
        [
          "",
          "### #{code(i.name)}",
          "",
          i.label,
          "",
          "Broken by: #{Enum.map_join(i.violated_by, ", ", &code(shown(&1)))}",
          "",
          "Kept by: #{Enum.map_join(i.satisfied_by, ", ", &code(shown(&1)))}",
          if(i.source, do: ["", "_Source: #{i.source}_"], else: [])
        ]
      end
    ]
  end

  # A title's name: the name in the code and the label, or for the owner the label.
  defp title_name(%{audience: :owner} = site, d), do: named(site, d)
  defp title_name(_site, d), do: code(d.name) <> label(d)

  defp domain_link(%{audience: :owner} = site), do: link("Domain #{site.domain.name}", "index.md")
  defp domain_link(site), do: link("Domain #{code(site.domain.name)}", "index.md")

  # A value's type, or for the owner the members of its enum by their labels.
  defp value_type(%{audience: :owner}, %{type: {:enum, members}}) do
    "One of: " <>
      Enum.map_join(members, ", ", fn
        {_member, label} -> label
        member -> code(member)
      end) <> "."
  end

  defp value_type(%{audience: :owner}, _v), do: nil

  defp value_type(site, v),
    do: if(v.type, do: row(["Type: ", type_link(site, v.type)]), else: "A value with fields.")

  # Every declaration with a field of the type, and every value or entity with one.
  defp used_by(site, name) do
    aliases =
      for v <- site.domain.values,
          mentions?(v.type, name),
          do: bullet(["value ", link(named(site, v), value_path(v.name))])

    section("Used by", aliases ++ holders(site, &mentions?(&1.type, name)), & &1)
  end

  # Every declaration, value and entity with a field `wanted` says yes to. With
  # `:identity_once`, a command's or an event's fields leave out its unit's identity,
  # which the unit's own entry stands for.
  defp holders(site, wanted, identity \\ :each) do
    in_domain =
      for(
        v <- site.domain.values,
        Enum.any?(v.fields, wanted),
        do: bullet(["value ", link(named(site, v), value_path(v.name))])
      ) ++
        for e <- site.domain.entities,
            Enum.any?(e.fields, wanted),
            do: bullet(["entity ", link(named(site, e), entity_path(e.name))])

    in_contracts =
      for model <- site.contracts,
          {key, declaration, fields} <- field_holders(model),
          Enum.any?(own_fields(model, key, declaration, fields, identity), wanted) do
        bullet([
          kind_word(key, declaration),
          " ",
          link(named(site, declaration), holder_path(model, key, declaration)),
          if(site.audience == :owner,
            do: " of " <> contract_name(site, model),
            else: " of #{inspect(model.module)}"
          )
        ])
      end

    in_domain ++ in_contracts
  end

  defp own_fields(model, key, declaration, fields, :identity_once)
       when key in [:commands, :events] do
    unit = Enum.find(model.units, &(&1.name == declaration.unit))
    Enum.reject(fields, &(&1.name in unit.identity))
  end

  defp own_fields(_model, _key, _declaration, fields, _identity), do: fields

  defp mentions?({:list, inner}, name), do: mentions?(inner, name)
  defp mentions?(type, name), do: type == name

  defp field_holders(model) do
    Enum.concat([
      for(u <- model.units, do: {:unit, u, u.state.fields}),
      for(c <- model.commands, do: {:commands, c, c.fields}),
      for(e <- model.events, do: {:events, e, e.fields}),
      for(pm <- model.process_managers, do: {:process_managers, pm, pm.state.fields}),
      for(r <- model.read_models, do: {:read_models, r, r.fields}),
      for(q <- model.queries, do: {:queries, q, q.params}),
      for(
        s <- model.domain_services,
        do: {:domain_services, s, Enum.flat_map(s.functions, &[&1.returns | &1.arguments])}
      )
    ])
  end

  defp holder_path(model, :unit, unit), do: unit_path(model, unit)
  defp holder_path(model, key, declaration), do: declaration_path(model, key, declaration.name)

  defp kind_word(:unit, unit), do: Atom.to_string(unit.kind)

  defp kind_word(key, _declaration) do
    {_, _, word} = List.keyfind(@kinds, key, 0)
    String.downcase(word)
  end

  defp entity_page(site, e) do
    [
      "# Entity #{title_name(site, e)}",
      "",
      domain_link(site),
      "",
      facts([
        row(["Context: ", link(context_name(site, e.context), context_path(e.context))]),
        code_fact(site, "Identified by #{code(e.identity)}."),
        if(e.source, do: "_Source: #{e.source}_")
      ]),
      fields_section(site, "Fields", e.fields),
      section("Referred to by", holders(site, &refers_to?(site, &1, {:entity, e.name})), & &1)
    ]
    |> Enum.reject(&is_nil/1)
  end

  # --- a context ---------------------------------------------------------------------

  defp context_page(site, c) do
    d = site.domain
    contracts = Enum.filter(site.contracts, &(&1.context == c.name))

    relations =
      for r <- d.relations,
          c.name in (r.between ++ [r.upstream, r.downstream]),
          do: relation(site, r)

    [
      "# Context #{title_name(site, c)}",
      "",
      context_header(site, c),
      if(c.source, do: ["", "_Source: #{c.source}_"], else: []),
      "",
      "## Contracts",
      "",
      case contracts do
        [] ->
          "_No contract._"

        _ ->
          for m <- contracts,
              do: bullet([link(contract_name(site, m), contract_path(m))])
      end,
      section("Relations", relations, & &1),
      glossary(site, c)
    ]
  end

  defp context_header(%{audience: :owner} = site, c) do
    subdomain = Enum.find(site.domain.subdomains, &(&1.name == c.subdomain))

    row([
      domain_link(site),
      " · subdomain #{if subdomain, do: subdomain.label, else: c.subdomain}"
    ])
  end

  defp context_header(site, c) do
    d = site.domain

    row([
      domain_link(site),
      " · subdomain #{code(c.subdomain)} · written in #{code(c.language || d.language)}"
    ])
  end

  # The term's word in another context, by that context's name or, for the owner, its
  # label.
  defp across(%{audience: :owner} = site, name, text) do
    for relation <- site.domain.relations,
        [first_end, second_end] = EhOsContract.Domain.Build.sides(relation),
        [first, second] <- Map.get(relation, :terms, []),
        {own, word, other, other_word} <- [
          {first_end, first, second_end, second},
          {second_end, second, first_end, first}
        ],
        own == name and word == text do
      where = context_or_external_name(site, other)
      ~s|_In #{where} (#{relation_type(site, relation)}): "#{other_word}"._|
    end
  end

  defp across(site, name, text), do: EhOsContract.Glossary.across(site.domain, name, text)

  defp context_or_external_name(site, name) do
    if Enum.any?(site.domain.contexts, &(&1.name == name)),
      do: context_name(site, name),
      else: external_name(site, name)
  end

  defp glossary(_site, %{terms: []}), do: ["", "## Glossary", "", "_No terms._"]

  defp glossary(site, c) do
    [
      "",
      "## Glossary",
      for t <- c.terms do
        [
          "",
          "### #{t.text}",
          "",
          t.definition,
          avoid(t.avoid),
          for(line <- across(site, c.name, t.text), do: ["", line]),
          if(t.source, do: ["", "_Source: #{t.source}_"], else: []),
          for tr <- t.translations do
            ["", "_#{tr.language}_: **#{tr.text}** — #{tr.definition}", avoid(tr.avoid)]
          end
        ]
      end
    ]
  end

  defp avoid([]), do: []

  defp avoid(words) do
    for w <- words do
      if w.reason,
        do: ["", ~s|_Avoid "#{w.text}"._ #{w.reason}|],
        else: ["", ~s|_Avoid "#{w.text}"._|]
    end
  end

  # --- a contract --------------------------------------------------------------------

  defp contract_pages(site, model) do
    declarations =
      for({key, _, _} <- @kinds, d <- Map.fetch!(model, key), do: {key, d}) ++
        for u <- model.units, do: {:unit, u}

    [{contract_path(model), contract_page(site, model)}] ++
      for {key, d} <- declarations do
        {holder_path(model, key, d), declaration_page(site, model, key, d)}
      end
  end

  defp contract_page(site, model) do
    [
      "# Contract #{contract_name(site, model)}",
      "",
      row([
        domain_link(site),
        " · context ",
        link(context_name(site, model.context), context_path(model.context)),
        code_fact(site, [" · version #{code(model.version)} · ", link("graph", graph_path(model))])
      ]),
      section("Units", model.units, &declaration_bullet(site, model, :unit, &1)),
      for {key, _dir, word} <- @kinds, key not in [:commands, :events] do
        section(plural(word), Map.fetch!(model, key), &declaration_bullet(site, model, key, &1))
      end,
      consumes_section(site, model),
      including_processes(site, model),
      code_fact(
        site,
        section("Published", model.publishes, fn p ->
          bullet([
            "#{code(p.name)}, published as #{code(p.as)}, from ",
            event_link(site, model, p.from)
          ])
        end)
      ),
      scenarios(site, model, model.scenarios)
    ]
  end

  # Plan DD, P2e (#220): the process modules whose runs this contract's events are in.
  defp including_processes(site, model) do
    lines =
      for {p, events} <- site.processes,
          mine = for(e <- events, e.contract == model.module, do: e.name),
          mine != [] do
        bullet(
          process_link(site, p) ++
            [" · includes "] ++
            joined(Enum.map(mine, &event_link(site, model, &1)))
        )
      end

    section("Processes that include its events", lines, & &1)
  end

  defp plural("Policy"), do: "Policies"
  defp plural("Query"), do: "Queries"
  defp plural(word), do: word <> "s"

  defp declaration_bullet(site, model, key, d),
    do: bullet(linked(site, d, holder_path(model, key, d)))

  defp process_link(%{audience: :owner}, p), do: [link(p.label, process_path(p))]
  defp process_link(_site, p), do: [link(code(p.id), process_path(p)), " — #{p.label}"]

  # `%{amount: 3, unit: :day}` as "3 days", and what the owner has not confirmed.
  defp duration(%{amount: _, unit: _} = d), do: EhOsContract.Duration.declared(d)

  defp duration({amount, unit} = d) when is_integer(amount) and is_atom(unit),
    do: EhOsContract.Duration.declared(d)

  defp duration(other), do: code(shown(other))

  defp consumes_section(site, model) do
    section("Consumed", model.consumes, fn
      # Each event linked to the sibling's page, under the name it has here.
      %{kind: :contract, from: from, events: events} = c ->
        sibling = Enum.find(site.contracts, &(&1.module == from))

        target =
          if sibling,
            do: link(contract_name(site, sibling), contract_path(sibling)),
            else: code(inspect(from))

        renames = Map.get(c, :renames, %{})

        consumed =
          for e <- events do
            name =
              if sibling,
                do: link(consumed_event(site, sibling, e), declaration_path(sibling, :events, e)),
                else: code(e)

            as = Map.get(renames, e)
            [name, code_fact(site, if(as && as != e, do: " as #{code(as)}"))]
          end

        bullet([target, ": " | joined(consumed)])

      %{kind: :published} = c ->
        code_fact(site, "- #{code(c.from)}, received as #{code(c.as)}")
    end)
  end

  defp scenarios(_site, _model, []), do: []

  defp scenarios(site, model, scenarios) do
    [
      "",
      "## Scenarios",
      # The description, then what happens, as two paragraphs of one item.
      for s <- scenarios do
        ["", "- #{s.description}", "", "  " <> scenario_line(site, model, s)]
      end
    ]
  end

  # A name a scenario uses, as the page names it: the code's, or for the owner the label
  # of the declaration of the contract it names.
  defp said(%{audience: :owner} = site, model, key, name) do
    found =
      case key do
        :events ->
          owner_event(site, model, name)

        :commands ->
          Enum.find(model.commands, &(&1.name == name))

        :rules ->
          Enum.find(
            Enum.flat_map(model.units, & &1.invariants) ++ all_constraints(model),
            &(&1.name == name)
          )

        :timers ->
          Enum.find(timers(model), &(&1.name == name))

        :triggers ->
          Enum.find(model.commands ++ model.queries ++ timers(model), &(&1.name == name)) ||
            owner_event(site, model, name)
      end

    cond do
      found -> named(site, found)
      key in [:events, :triggers] and published?(model, name) -> received(site, name)
      true -> code(name)
    end
  end

  defp said(_site, _model, _key, name), do: code(name)

  defp published?(model, name),
    do: Enum.any?(model.consumes, &(&1.kind == :published and &1.as == name))

  defp timers(model), do: Enum.flat_map(model.process_managers, & &1.timers)

  # An event as the contract names it: its own, or a sibling's it consumes, under the
  # name it has there.
  defp owner_event(site, model, name) do
    with nil <- Enum.find(model.events, &(&1.name == name)),
         {:contract, from, original} <- Model.consumed(model, name),
         %{} = sibling <- Enum.find(site.contracts, &(&1.module == from)) do
      Enum.find(sibling.events, &(&1.name == original))
    else
      %{} = event -> event
      _ -> nil
    end
  end

  defp all_constraints(model) do
    for(c <- model.commands ++ model.queries, x <- Map.get(c, :constraints, []), do: x) ++
      for r <- model.policies ++ model.effects ++ model.process_managers,
          x <- Map.get(r, :constraints, []) ++ Map.get(r, :invariants, []),
          do: x
  end

  defp scenario_line(site, model, s) do
    say = &said(site, model, &1, &2)
    given = Enum.map(s.given, &say.(:events, &1.event))
    trigger = "#{s.trigger.kind} #{say.(:triggers, s.trigger.name)}"

    # What a process manager's scenario says of its timers and its end, too.
    outcome =
      [
        if(s.rejected, do: "rejected on #{say.(:rules, s.rejected)}"),
        if(s.expect != [],
          do: "expects #{Enum.map_join(s.expect, ", ", &say.(:events, &1.event))}"
        ),
        if(s.issues != [],
          do: "issues #{Enum.map_join(s.issues, ", ", &say.(:commands, &1.command))}"
        ),
        if(Map.get(s, :sets, []) != [],
          do: "sets #{Enum.map_join(s.sets, ", ", &say.(:timers, &1))}"
        ),
        if(Map.get(s, :cancels, []) != [],
          do: "cancels #{Enum.map_join(s.cancels, ", ", &say.(:timers, &1))}"
        ),
        if(Map.get(s, :ended), do: "ends the run"),
        if(Map.has_key?(s, :answers), do: "answers #{length(List.wrap(s.answers))} row(s)"),
        code_fact(
          site,
          if(Map.has_key?(s, :state),
            do: "holds " <> (s.state |> Map.keys() |> Enum.sort() |> Enum.map_join(", ", &code/1))
          )
        )
      ]
      |> Enum.reject(&is_nil/1)
      |> Enum.join(", ")
      |> blank("as declared")

    given = if given == [], do: "", else: "given #{Enum.join(given, ", ")}; "

    # The rules it shows (plan EP2), after what happens.
    shows =
      case Map.get(s, :illustrates, []) do
        [] -> ""
        names -> " — illustrates #{Enum.map_join(names, ", ", &say.(:rules, &1))}"
      end

    "#{given}#{trigger}; #{outcome}#{shows}"
  end

  # A declaration's rules: a command's and a query's constraints, and a reaction's
  # constraints and a process manager's invariants (plan EP2).
  defp rules(site, d) do
    [
      section("Constraints", Map.get(d, :constraints, []), &"- #{labelled(site, &1)}"),
      section("Invariants", Map.get(d, :invariants, []), &"- #{labelled(site, &1)}")
    ]
  end

  # --- a process module (plan DD, P2e (#220)) ---------------------------------------------

  # What a process module declares, the events of its stages each linked to its page in
  # the contract that declares it. The words are the ones the contract's page used for
  # its own process before a contract lost it (plan DD, P2h, #221).
  defp process_page(site, model, events) do
    p = Model.process(model)

    [
      "# Process #{if site.audience == :owner, do: p.label, else: "#{code(p.name)} — #{p.label}"}",
      "",
      row([
        domain_link(site),
        code_fact(site, [
          " · module #{code(inspect(model.module))} · version #{code(model.version)} · ",
          link("graph", graph_path(model))
        ])
      ]),
      if(p.source, do: ["", "_Source: #{p.source}_"], else: []),
      facts([
        # As the report and the dashboard say it; nothing for a model without `correlate`.
        code_fact(
          site,
          if(clause = EhOsContract.Report.Sentence.runs_per(Enum.map(p.correlate, &code/1)),
            do: "Runs: #{clause}."
          )
        ),
        if(p.accountable, do: accountable(site, p.accountable)),
        if(p.deadline, do: deadline(site, p.deadline))
      ]),
      process_stages(site, p, events),
      section(
        "Ends a run",
        for(e <- events, e.terminal, do: e),
        &bullet([included_event(site, %{&1 | terminal: false})])
      ),
      section("Promises", p.promises, &promise(site, events, &1)),
      resting(site, events, p.promises),
      process_scenarios(site, events, p, Map.get(model, :scenarios, []))
    ]
  end

  defp accountable(site, name) do
    case Enum.find(site.domain.actors, &(&1.name == name)) do
      nil -> "Accountable: #{code(name)}."
      actor -> "Accountable: #{labelled(site, actor)}."
    end
  end

  defp deadline(site, d) do
    "Deadline: #{duration(Map.delete(d, :unverified))} from the start of a run." <>
      unconfirmed(site, d)
  end

  # What the conformance report leaves out, said where it is declared.
  defp unconfirmed(site, %{unverified: true}) do
    marked = if site.audience == :owner, do: "", else: " (`unverified`)"
    " Not confirmed by the process owner#{marked}, so the conformance report leaves it out."
  end

  defp unconfirmed(_site, _declaration), do: ""

  # The stages in their order, each with its events grouped by the contract that
  # declares them. A stage none of whose includes resolves says so.
  defp process_stages(site, p, events) do
    stages =
      for {stage, index} <- Enum.with_index(p.stages, 1) do
        groups =
          case Model.stage_includes(events, stage.name) do
            [] ->
              ["_no included event resolves to a contract of the domain_"]

            includes ->
              includes
              |> Enum.map(fn {contract, group} ->
                [contract_ref(site, contract), ": "] ++
                  joined(Enum.map(group, &included_event(site, &1)))
              end)
              |> Enum.intersperse("; ")
          end

        row(["#{index}. #{labelled(site, stage)} — " | List.flatten(groups)])
      end

    ["", "## Stages", "" | stages]
  end

  defp contract_ref(site, module) do
    case Enum.find(site.contracts, &(&1.module == module)) do
      nil -> code(inspect(module))
      contract -> link(contract_name(site, contract), contract_path(contract))
    end
  end

  # An included event, linked to its page in its contract; plain text when that
  # contract is not among the pages.
  defp included_event(site, e) do
    name =
      case Enum.find(site.contracts, &(&1.module == e.contract)) do
        nil -> code(e.name)
        contract -> link(named(site, e.declaration), declaration_path(contract, :events, e.name))
      end

    [name, if(e.terminal, do: " (ends a run)")]
  end

  defp process_event(site, events, name) do
    case Enum.find(events, &(&1.name == name)) do
      nil -> code(name)
      e -> included_event(site, %{e | terminal: false})
    end
  end

  defp promise(site, events, pr) do
    event = &process_event(site, events, &1)

    bullet([
      if(site.audience == :owner, do: "After ", else: "#{code(pr.name)}: after "),
      event.(pr.from),
      ", eventually ",
      event.(pr.eventually),
      if(pr.within, do: " within #{duration(pr.within)}"),
      if(pr.or_else, do: [", or else ", event.(pr.or_else)]),
      case Map.get(pr, :waits_on, []) do
        [] ->
          []

        waits ->
          [", waiting on " | Enum.intersperse(Enum.map(waits, &external_name(site, &1)), ", ")]
      end,
      if(pr.unverified, do: [".", unconfirmed(site, pr)]),
      source_note(pr)
    ])
  end

  # The external systems the included events rest on, and those a promise waits on
  # through an earlier step: an outage of one suspends a promise instead of breaking it.
  defp resting(site, events, promises) do
    resting = for e <- events, x = e.declaration[:depends_on], x != nil, do: {x, e}
    waiting = for pr <- promises, x <- Map.get(pr, :waits_on, []), do: {x, pr}

    lines =
      for x <- (resting ++ waiting) |> Enum.map(&elem(&1, 0)) |> Enum.uniq() do
        external = Enum.find(site.domain.externals, &(&1.name == x))
        name = if external, do: labelled(site, external), else: code(x)
        on_it = for {^x, e} <- resting, do: included_event(site, %{e | terminal: false})
        waits = for {^x, pr} <- waiting, do: pr

        bullet(
          ["#{name}"] ++
            if(on_it == [], do: [], else: [" · what rests on it: " | joined(on_it)]) ++
            waiting_on(site, waits)
        )
      end

    case lines do
      [] ->
        []

      lines ->
        [
          "",
          "## External systems",
          "",
          "An outage of one suspends a promise whose events rest on it, or that waits on it, " <>
            "rather than breaking it.",
          "" | lines
        ]
    end
  end

  # The promises that wait on a system. The owner reads a promise by its rule, above, and
  # not by its name in the code.
  defp waiting_on(_site, []), do: []
  defp waiting_on(%{audience: :owner}, [_]), do: [" · a promise above waits on it"]

  defp waiting_on(%{audience: :owner}, waits),
    do: [" · #{length(waits)} promises above wait on it"]

  defp waiting_on(_site, waits),
    do: [" · the promises that wait on it: " | joined(Enum.map(waits, &code(&1.name)))]

  # A process module's scenarios: a promise judged at a moment, after what happened.
  defp process_scenarios(_site, _events, _p, []), do: []

  defp process_scenarios(site, events, p, scenarios) do
    [
      "",
      "## Scenarios",
      for s <- scenarios do
        happened =
          Enum.map(s.given, &process_said(site, events, &1.event)) ++
            Enum.map(s.outages, &"outage of #{external_name(site, &1.external)}")

        given = if happened == [], do: "", else: "given #{Enum.join(happened, ", ")}; "

        [
          "",
          "- #{s.description}",
          "",
          "  #{given}#{judged(site, events, p, s)}"
        ]
      end
    ]
  end

  # An event a process's scenario names, by its name or the owner's label.
  defp process_said(%{audience: :owner} = site, events, name) do
    case Enum.find(events, &(&1.name == name)) do
      nil -> code(name)
      e -> named(site, e.declaration)
    end
  end

  defp process_said(_site, _events, name), do: code(name)

  # The verdict a process's scenario expects. A promise has no label, so the owner reads
  # it by what it waits for.
  defp judged(%{audience: :owner} = site, events, p, s) do
    case Enum.find(p.promises, &(&1.name == s.promise.name)) do
      nil ->
        "the promise is #{s.verdict}"

      promise ->
        "the promise that after #{process_said(site, events, promise.from)} comes " <>
          "#{process_said(site, events, promise.eventually)} is #{s.verdict}"
    end
  end

  defp judged(_site, _events, _p, s) do
    via = if s.via, do: " by #{code(s.via)}", else: ""
    "promise #{code(s.promise.name)} is #{s.verdict}#{via}"
  end

  # --- one declaration -----------------------------------------------------------------

  defp declaration_page(site, model, key, d) do
    [
      "# #{title(key, d)} #{declaration_title(site, d)}",
      "",
      declaration_header(site, model),
      if(Map.get(d, :source), do: ["", "_Source: #{d.source}_"], else: []),
      body(site, model, key, d),
      scenarios(site, model, Enum.filter(model.scenarios, &about?(&1, key, d)))
    ]
  end

  # Where a declaration is: its contract and its context, or for the owner its contract,
  # named after its context.
  defp declaration_header(%{audience: :owner} = site, model),
    do: row(["In ", link(contract_name(site, model), contract_path(model))])

  defp declaration_header(site, model) do
    row([
      "Contract ",
      link(contract_name(site, model), contract_path(model)),
      " · context ",
      link(context_name(site, model.context), context_path(model.context))
    ])
  end

  defp declaration_title(%{audience: :owner} = site, d), do: "— " <> named(site, d)
  defp declaration_title(_site, d), do: code(d.name) <> label(d)

  defp title(:unit, unit), do: String.capitalize(Atom.to_string(unit.kind))

  defp title(key, _d) do
    {_, _, word} = List.keyfind(@kinds, key, 0)
    word
  end

  defp about?(%{target: %{kind: kind, name: name}}, :unit, %{kind: kind, name: name}), do: true
  defp about?(%{trigger: %{kind: :command, name: name}}, :commands, %{name: name}), do: true

  defp about?(%{target: %{kind: kind, name: name}}, key, %{name: name})
       when {kind, key} in [
              policy: :policies,
              process_manager: :process_managers,
              query: :queries
            ],
       do: true

  defp about?(_scenario, _key, _d), do: false

  defp body(site, model, :unit, u) do
    commands = Enum.filter(model.commands, &(&1.unit == u.name))
    events = Enum.filter(model.events, &(&1.unit == u.name))

    [
      facts([
        code_fact(site, "Identity: #{Enum.map_join(u.identity, ", ", &code/1)}."),
        # Plan DD, L2 (#272): derived, never declared.
        if(EhOsContract.Refusals.records_only?(model, u),
          do: "Records only: no command it takes can be refused."
        )
      ]),
      section("Consults", u.consults, &consults(site, model, &1)),
      section("Invariants", u.invariants, fn i ->
        rejecting = for c <- commands, i.name in c.rejects, do: command_link(site, model, c.name)
        bullet(["#{labelled(site, i)} · rejected by " | joined(rejecting)])
      end),
      fields_section(site, "State", u.state.fields),
      section("Commands", commands, &declaration_bullet(site, model, :commands, &1)),
      section("Events", events, &declaration_bullet(site, model, :events, &1)),
      # Plan DD, L3 (#286): the fields that identify it, in this contract and others. A
      # unit whose identity does is listed once, not with each of its commands and events.
      section(
        "Referred to by",
        holders(site, &refers_to?(site, &1, {:unit, model, u.name}), :identity_once),
        & &1
      )
    ]
  end

  defp body(site, model, :commands, c) do
    unit = Enum.find(model.units, &(&1.name == c.unit))

    [
      facts([
        row([
          "#{String.capitalize(Atom.to_string(unit.kind))} ",
          link(named(site, unit), unit_path(model, unit))
        ]),
        "Issued by: #{Enum.map_join(List.wrap(c.by), ", ", &actor_name(site, &1)) |> blank("no actor")}.",
        row(["Emits: " | joined(Enum.map(c.emits, &event_link(site, model, &1)))]),
        if(c.rejects != [],
          do: "Rejects on: #{Enum.map_join(c.rejects, ", ", &said(site, model, :rules, &1))}."
        ),
        code_fact(
          site,
          if(Map.get(c, :creates),
            do: "Creates its #{unit.kind}, whose identity the library gives."
          )
        )
      ]),
      rules(site, c),
      issued_by_reactions(site, model, c),
      fields_section(site, "Fields", c.fields)
    ]
  end

  defp body(site, model, :events, e) do
    unit = Enum.find(model.units, &(&1.name == e.unit))
    emitted = for c <- model.commands, e.name in c.emits, do: command_link(site, model, c.name)

    [
      facts([
        row([
          "#{String.capitalize(Atom.to_string(unit.kind))} ",
          link(named(site, unit), unit_path(model, unit))
        ]),
        code_fact(site, if(e.type, do: "Stored as #{code(e.type)}.")),
        row(["Emitted by: " | joined(emitted)]),
        if(e.recorded_by != [],
          do: "Recorded by: #{Enum.map_join(e.recorded_by, ", ", &actor_name(site, &1))}."
        )
      ]),
      readers(site, model, e),
      fields_section(site, "Fields", e.fields)
    ]
  end

  defp body(site, model, :policies, p) do
    [
      facts([
        row(["Handles: " | joined(Enum.map(List.wrap(p.handles), &event_link(site, model, &1)))]),
        row(["Issues: " | joined(Enum.map(List.wrap(p.issues), &command_link(site, model, &1)))]),
        code_fact(site, "Delivered #{code(p.delivery)}."),
        code_fact(site, Doc.idempotency(p))
      ]),
      rules(site, p)
    ]
  end

  defp body(site, model, :effects, e) do
    [
      facts([
        row(["Handles: " | joined(Enum.map(List.wrap(e.handles), &event_link(site, model, &1)))]),
        calls(site, e),
        code_fact(site, "Delivered #{code(e.delivery)}."),
        code_fact(site, Doc.idempotency(e))
      ]),
      rules(site, e)
    ]
  end

  defp body(site, model, :process_managers, pm) do
    # What a reaction does: the commands it issues, the timers it sets and cancels.
    reaction = fn r ->
      issues = Enum.map(Map.get(r, :issues, []), &command_link(site, model, &1))

      timers =
        for {word, key} <- [sets: :sets, cancels: :cancels],
            t <- List.wrap(Map.get(r, key)),
            do: "#{word} timer #{said(site, model, :timers, t)}"

      # `on` may name one of the manager's own timers, which fires, rather than an event.
      trigger =
        if Enum.any?(pm.timers, &(&1.name == r.event)),
          do: "timer #{said(site, model, :timers, r.event)}",
          else: event_link(site, model, r.event)

      bullet([trigger, " → " | joined(issues ++ timers)])
    end

    [
      facts([
        code_fact(site, "Runs are told by #{Enum.map_join(pm.correlate, ", ", &code/1)}."),
        code_fact(site, Doc.idempotency(pm))
      ]),
      section("Starts on", pm.starts_on, reaction),
      section("Reacts to", pm.on, reaction),
      section("Timers", pm.timers, fn t ->
        issues = Enum.map(t.issues, &command_link(site, model, &1))
        arrow = if issues == [], do: [], else: [" → " | joined(issues)]

        bullet(["#{labelled(site, t)} (#{when_fires(site, t)})" | arrow ++ [source_note(t)]])
      end),
      section("Ends on", pm.ends_on, &bullet([event_link(site, model, &1)])),
      rules(site, pm),
      fields_section(site, "State", pm.state.fields)
    ]
  end

  defp body(site, model, :read_models, r) do
    queries =
      for q <- model.queries, q.reads == r.name, do: declaration_bullet(site, model, :queries, q)

    [
      facts([
        row([
          "Projects: " | joined(Enum.map(List.wrap(r.projects), &event_link(site, model, &1)))
        ]),
        code_fact(site, "Delivered #{code(r.delivery)}.")
      ]),
      section("Queries", queries, & &1),
      fields_section(site, "Fields", r.fields)
    ]
  end

  defp body(site, model, :queries, q) do
    read_model = Enum.find(model.read_models, &(&1.name == q.reads))

    [
      facts([
        row([
          "Reads: ",
          link(named(site, read_model), declaration_path(model, :read_models, read_model.name))
        ]),
        "Asked by: #{Enum.map_join(List.wrap(q.by), ", ", &actor_name(site, &1)) |> blank("no actor")}.",
        "Returns #{if q.returns == :one, do: "one row or none", else: "rows"}.",
        code_fact(site, if(q.scope, do: "Narrowed by #{code(q.scope)}."))
      ]),
      rules(site, q),
      fields_section(site, "Parameters", q.params)
    ]
  end

  defp body(%{audience: :owner} = site, _model, :domain_services, s) do
    for f <- s.functions do
      ["", "## #{f.label}" | for(r <- f.rules, do: ["", "- #{labelled(site, r)}"])]
    end
  end

  defp body(site, _model, :domain_services, s) do
    for f <- s.functions do
      arguments = for a <- f.arguments, do: [code(a.name), " ", type_link(site, a.type)]

      [
        "",
        "## #{code(f.name)} — #{f.label}",
        "",
        row(["Takes " | joined(arguments)]),
        "",
        row([
          "Returns ",
          type_link(site, f.returns.type),
          if(f.returns.optional, do: ", or nothing", else: "")
        ]),
        for r <- f.rules do
          [
            "",
            "- **#{code(r.name)}** — #{r.label}",
            for(
              {args, result} <- r.examples,
              do:
                "  - `#{f.name}(#{Enum.map_join(args, ", ", &shown/1)})` returns `#{shown(result)}`"
            )
          ]
        end
      ]
    end
  end

  # The systems an effect calls, and their operations: by name, or for the owner by label.
  defp calls(%{audience: :owner} = site, e) do
    case List.wrap(e.calls) do
      [] ->
        nil

      systems ->
        operations = Map.get(e, :operations, [])

        named =
          for x <- systems do
            external = Enum.find(site.domain.externals, &(&1.name == x))
            declared = if external, do: Map.get(external, :operations, []), else: []

            ops =
              for %{external: ^x, name: op} <- operations do
                case Enum.find(declared, &(&1.name == op)) do
                  nil -> code(op)
                  operation -> named(site, operation)
                end
              end

            external_name(site, x) <> if(ops == [], do: "", else: " (#{Enum.join(ops, ", ")})")
          end

        "Calls: #{Enum.join(named, ", ")}."
    end
  end

  defp calls(_site, e), do: if(called = Doc.called(e), do: "Calls: #{called}.")

  # Facts about a declaration, each a paragraph of its own.
  defp facts(lines), do: lines |> Enum.reject(&is_nil/1) |> Enum.flat_map(&["", &1])

  # An example as written, the same on every machine: `inspect/1` prints a map's keys
  # in the order of their atoms, which depends on when each atom was made, so a page
  # would differ between two builds and `--check` would fail on one of them.
  defp shown(%{__struct__: _} = struct), do: inspect(struct)

  defp shown(%{} = map) do
    pairs =
      map
      |> Enum.sort_by(fn {key, _} -> to_string(key) end)
      |> Enum.map_join(", ", fn
        {key, value} when is_atom(key) -> "#{key}: #{shown(value)}"
        {key, value} -> "#{inspect(key)} => #{shown(value)}"
      end)

    "%{#{pairs}}"
  end

  defp shown(list) when is_list(list), do: "[#{Enum.map_join(list, ", ", &shown/1)}]"

  defp shown(tuple) when is_tuple(tuple),
    do: "{#{tuple |> Tuple.to_list() |> Enum.map_join(", ", &shown/1)}}"

  defp shown(term), do: inspect(term)

  defp blank("", word), do: word
  defp blank(text, _word), do: text

  defp consults(site, model, c) do
    how =
      cond do
        site.audience == :owner and is_binary(Map.get(c, :where)) -> " where #{c.where}"
        site.audience == :owner -> ""
        Map.get(c, :match, []) != [] -> " by #{Enum.map_join(c.match, ", ", &code/1)}"
        is_binary(Map.get(c, :where)) -> " where #{c.where}"
        true -> ""
      end

    bullet([event_link(site, model, c.event), how])
  end

  # The reactions of this contract that issue the command, each once however many of
  # its ways in issue it, a timer's included.
  defp issued_by_reactions(site, model, c) do
    reactions =
      for %{command: command} = r <- EhOsContract.Reactions.issued(model),
          command == c.name,
          uniq: true,
          do: {r.kind, r.reaction}

    section("Issued by reactions", reactions, fn
      {:policy, p} ->
        bullet(["policy ", declaration_bullet_link(site, model, :policies, p)])

      {:process_manager, pm} ->
        bullet(["process manager ", declaration_bullet_link(site, model, :process_managers, pm)])
    end)
  end

  defp declaration_bullet_link(site, model, key, d),
    do: link(named(site, d), holder_path(model, key, d))

  # Who reads the event: this contract's consumers, and the contracts consuming it.
  defp readers(site, model, e) do
    own =
      Enum.concat([
        for(p <- model.policies, e.name in List.wrap(p.handles), do: {"policy", :policies, p}),
        for(x <- model.effects, e.name in List.wrap(x.handles), do: {"effect", :effects, x}),
        for(
          pm <- model.process_managers,
          e.name in (Enum.map(pm.starts_on ++ pm.on, & &1.event) ++ pm.ends_on),
          do: {"process manager", :process_managers, pm}
        ),
        for(
          r <- model.read_models,
          e.name in List.wrap(r.projects),
          do: {"read model", :read_models, r}
        )
      ])
      |> Enum.map(fn {word, key, d} ->
        bullet([word, " ", declaration_bullet_link(site, model, key, d)])
      end)

    others =
      for other <- site.contracts,
          other.module != model.module,
          %{kind: :contract, from: from, events: events} <- other.consumes,
          from == model.module,
          e.name in events do
        bullet(["contract ", link(contract_name(site, other), contract_path(other))])
      end

    section("Read by", own ++ others, & &1)
  end
end
