defmodule EhOsContract.Pages do
  @moduledoc """
  A domain and its contracts as Markdown pages, one per element, linked to each
  other (ESDM's `documentation`; plan EL3). `mix eh_os_contract.pages --output <dir>`
  writes them.

      index.md                                    the domain, with its tree
      values/money.md                             a value: its type, invariants, examples
      entities/<name>.md                          an entity
      settlement/index.md                         a context: glossary, relations, contracts
      settlement/visit_settlement/index.md        a contract: its process and declarations
      settlement/visit_settlement/commands/record_payment.md
      settlement/visit_settlement/events/payment_recorded.md
      settlement/visit_settlement/aggregates/visit_settlement.md
      …/dcbs, policies, effects, process_managers, read_models, queries, domain_services

  A contract's directory is its module's last segment, underscored. Each kind has a
  directory of its own, since a contract's namespaces overlap: a read model may share
  a unit's name. Every link is relative, so the pages read the same wherever the
  directory goes — a repository, ExDoc's `extras`, a file browser.

  The words around the model are the library's, in English; labels, terms,
  definitions and scenario descriptions are the client's, printed as declared.
  Everything comes in declaration order, as every reader of the model prints (v2 §9).
  Each page starts with `marker/1` of its domain, which is how the task tells the
  pages it wrote for that domain from files it must leave alone — a person's, or
  another domain's pages in the same directory.
  """

  alias EhOsContract.Model

  # A contract's declarations with a page of their own: the model's key, the
  # directory, and the word for one.
  @kinds [
    {:commands, "commands", "Command"},
    {:events, "events", "Event"},
    {:policies, "policies", "Policy"},
    {:effects, "effects", "Effect"},
    {:process_managers, "process_managers", "Process manager"},
    {:read_models, "read_models", "Read model"},
    {:queries, "queries", "Query"},
    {:domain_services, "domain_services", "Domain service"}
  ]

  @doc """
  The first line of every page of the domain named `name`, which tells a page
  generated for it from any other file.
  """
  @spec marker(atom()) :: String.t()
  def marker(name),
    do:
      "<!-- Generated by mix eh_os_contract.pages for domain #{name}. Edits are overwritten. -->"

  @doc """
  The pages of `domain`, a domain module or its model, and of `contracts`, the v2
  contract modules or models naming it, as `%{relative path => Markdown}`. Contracts
  naming another domain are left out. Raises when two contracts of one context would
  share a directory, when two elements would share a page, and when a name is not
  snake_case, since pages are named after names.
  """
  @spec render(module() | map(), [module() | map()]) :: %{String.t() => String.t()}
  def render(domain, contracts) do
    domain = Model.fetch(domain)

    contracts =
      contracts
      |> Enum.map(&Model.fetch/1)
      |> Enum.filter(&(&1.domain == domain.module))

    distinct!(contracts)
    site = %{domain: domain, contracts: contracts}

    [{"index.md", domain_page(site)}]
    |> Enum.concat(for v <- domain.values, do: {value_path(v.name), value_page(site, v)})
    |> Enum.concat(for e <- domain.entities, do: {entity_path(e.name), entity_page(site, e)})
    |> Enum.concat(for c <- domain.contexts, do: {context_path(c.name), context_page(site, c)})
    |> Enum.concat(Enum.flat_map(contracts, &contract_pages(site, &1)))
    |> paths!()
    |> Map.new(fn {path, lines} -> {path, page(domain.name, path, lines)} end)
  end

  # A path is made of names, and the domain's are not held to snake_case the way a
  # contract's are (N1): one written `:"../x"` would write outside the directory, and
  # one with a space would break every link to it. Two elements of one path would
  # leave one of them without a page.
  defp paths!(pages) do
    for {path, _lines} <- pages,
        segment <- path |> String.trim_trailing(".md") |> Path.split(),
        not (segment =~ ~r/^[a-z][a-z0-9_]*$/) do
      raise ArgumentError,
            "the page #{inspect(path)} would be named after #{inspect(segment)}; a page is " <>
              "named after a snake_case name"
    end

    for path <- pages |> Enum.map(&elem(&1, 0)) |> EhOsContract.DslRules.duplicates(& &1) do
      raise ArgumentError, "two elements would have the page #{path}; rename one of them"
    end

    pages
  end

  defp distinct!(contracts) do
    for {{context, slug}, [first, second | _]} <-
          Enum.group_by(contracts, &{&1.context, slug(&1)}, & &1.module) do
      raise ArgumentError,
            "#{inspect(first)} and #{inspect(second)} would share the directory " <>
              "#{context}/#{slug}; a context's contracts have pages under the last segment of " <>
              "their module's name"
    end
  end

  # A page is its lines with the links resolved against where it is.
  defp page(name, path, lines) do
    body =
      lines
      |> List.flatten()
      |> Enum.reject(&is_nil/1)
      |> Enum.map(&line(&1, path))
      |> Enum.join("\n")
      |> String.replace(~r/\n{3,}/, "\n\n")
      |> String.trim_trailing()

    Enum.join([marker(name), "", body, ""], "\n")
  end

  # A line is a string, a link, or a row of both.
  defp line({:row, parts}, path),
    do: parts |> List.flatten() |> Enum.reject(&is_nil/1) |> Enum.map_join(&line(&1, path))

  defp line({:link, text, to}, path), do: "[#{text}](#{relative(path, to)})"
  defp line(text, _path) when is_binary(text), do: text

  # --- paths and links ------------------------------------------------------------

  defp value_path(name), do: "values/#{name}.md"
  defp entity_path(name), do: "entities/#{name}.md"
  defp context_path(name), do: "#{name}/index.md"
  defp contract_dir(model), do: "#{model.context}/#{slug(model)}"
  defp contract_path(model), do: "#{contract_dir(model)}/index.md"
  defp slug(model), do: model.module |> Module.split() |> List.last() |> Macro.underscore()

  defp declaration_path(model, key, name) do
    {_, dir, _} = List.keyfind(@kinds, key, 0) || {key, unit_dir(key), nil}
    "#{contract_dir(model)}/#{dir}/#{name}.md"
  end

  defp unit_dir(:aggregate), do: "aggregates"
  defp unit_dir(:dcb), do: "dcbs"

  defp unit_path(model, unit), do: declaration_path(model, unit.kind, unit.name)

  # `to`, from the directory of `from`.
  defp relative(from, to) do
    from_dirs = from |> Path.split() |> Enum.drop(-1)
    to_parts = Path.split(to)
    common = common_length(from_dirs, to_parts)
    ups = List.duplicate("..", length(from_dirs) - common)
    Enum.join(ups ++ Enum.drop(to_parts, common), "/")
  end

  defp common_length([a | as], [a | bs]) when bs != [], do: 1 + common_length(as, bs)
  defp common_length(_as, _bs), do: 0

  defp link(text, to), do: {:link, text, to}
  defp code(name), do: "`#{name}`"

  # An event as the contract names it: its own page, a sibling's, or plain text for
  # one received from another application.
  defp event_link(site, model, name) do
    case Enum.find(model.events, &(&1.name == name)) do
      %{} ->
        link(code(name), declaration_path(model, :events, name))

      nil ->
        with {:contract, from, original} <- Model.consumed(model, name),
             %{} = sibling <- Enum.find(site.contracts, &(&1.module == from)) do
          link("#{code(name)} of #{inspect(from)}", declaration_path(sibling, :events, original))
        else
          _ -> "#{code(name)} (received)"
        end
    end
  end

  defp command_link(model, name), do: link(code(name), declaration_path(model, :commands, name))

  defp joined([]), do: ["—"]

  defp joined(items) do
    Enum.intersperse(items, ", ")
  end

  # --- fields ----------------------------------------------------------------------

  defp fields_table(_site, []), do: ["_No fields._"]

  defp fields_table(site, fields) do
    rows =
      for f <- fields do
        [
          "| ",
          code(f.name),
          " | ",
          type(site, f),
          " | ",
          Map.get(f, :label) || "",
          " | ",
          notes(f),
          " |"
        ]
      end

    ["| Field | Type | Label | |", "| --- | --- | --- | --- |" | Enum.map(rows, &row/1)]
  end

  # A row of a table with links in it, joined when the page resolves them.
  defp row(parts), do: {:row, parts}

  defp type(site, %{refers_to: entity, type: {:list, inner}}) when entity != nil,
    do: ["list of ", code(inspect(inner)), " of ", entity_link(site, entity)]

  defp type(site, %{refers_to: entity, type: type}) when entity != nil,
    do: [code(inspect(type)), " of ", entity_link(site, entity)]

  defp type(site, %{type: type}), do: type_link(site, type)

  defp type_link(site, {:list, inner}), do: ["list of ", type_link(site, inner)]

  defp type_link(site, name) when is_atom(name) do
    if Enum.any?(site.domain.values, &(&1.name == name)),
      do: link(code(name), value_path(name)),
      else: code(inspect(name))
  end

  defp type_link(_site, type), do: code(inspect(type))

  defp entity_link(site, name) do
    if Enum.any?(site.domain.entities, &(&1.name == name)),
      do: link(code(name), entity_path(name)),
      else: code(name)
  end

  defp notes(field) do
    [
      if(Map.get(field, :optional), do: "optional"),
      if(p = Map.get(field, :personal), do: "personal to #{code(p)}"),
      if(s = Map.get(field, :subject), do: "identifies a #{code(s)}"),
      if(i = Map.get(field, :issued_by), do: "issued by #{code(i)}")
    ]
    |> Enum.reject(&is_nil/1)
    |> Enum.join(", ")
  end

  # --- the domain ------------------------------------------------------------------

  defp domain_page(site) do
    d = site.domain
    tree = EhOsContract.View.render(d, site.contracts)

    [
      "# Domain #{code(d.name)}",
      "",
      "Written in #{code(d.language)}. Version #{code(d.version)}.",
      "",
      "## Contexts",
      "",
      for c <- d.contexts do
        subdomain = Enum.find(d.subdomains, &(&1.name == c.subdomain))
        kind = if subdomain, do: "#{subdomain.type} ", else: ""

        bullet([
          link(code(c.name), context_path(c.name)),
          " — #{c.label} · #{kind}subdomain #{code(c.subdomain)}"
        ])
      end,
      section("Subdomains", d.subdomains, &"- #{code(&1.name)} — #{&1.label} · #{&1.type}"),
      section("Values", d.values, &bullet([link(code(&1.name), value_path(&1.name)), label(&1)])),
      section(
        "Entities",
        d.entities,
        &bullet([link(code(&1.name), entity_path(&1.name)), " — #{&1.label}"])
      ),
      section("Actors", d.actors, &actor/1),
      section("Subjects of personal data", d.subjects, &"- #{code(&1.name)} — #{&1.label}"),
      section("External systems", d.externals, &external/1),
      section("Relations between contexts", d.relations, &relation(site, &1)),
      "",
      "## Tree",
      "",
      "```",
      tree,
      "```"
    ]
  end

  defp bullet(parts), do: row(["- " | List.wrap(parts)])

  defp label(%{label: label}) when is_binary(label), do: " — #{label}"
  defp label(_), do: ""

  defp section(_title, [], _fun), do: []
  defp section(title, items, fun), do: ["", "## #{title}", "" | Enum.map(items, fun)]

  defp actor(a) do
    extra =
      [
        if(a.backed_by, do: "backed by #{code(a.backed_by)}"),
        if(a.context, do: "context #{code(a.context)}"),
        if(a.scope != [], do: "scope #{Enum.map_join(a.scope, ", ", &code/1)}")
      ]
      |> Enum.reject(&is_nil/1)

    "- #{code(a.name)} — #{a.label} · #{a.kind}#{Enum.map_join(extra, "", &" · #{&1}")}"
  end

  defp external(e) do
    extra =
      [
        if(e.unavailable_looks_like, do: "unavailable looks like: #{e.unavailable_looks_like}"),
        if(e.expected_latency, do: "expected latency #{duration(e.expected_latency)}")
      ]
      |> Enum.reject(&is_nil/1)

    "- #{code(e.name)} — #{e.label} · #{e.direction}#{Enum.map_join(extra, "", &" · #{&1}")}"
  end

  defp relation(site, %{between: [_ | _] = between} = r),
    do: bullet(["#{r.type} between " | joined(Enum.map(between, &context_or_external(site, &1)))])

  defp relation(site, r) do
    bullet([
      "#{r.type}: ",
      context_or_external(site, r.upstream),
      " upstream of ",
      context_or_external(site, r.downstream)
    ])
  end

  defp context_or_external(site, name) do
    if Enum.any?(site.domain.contexts, &(&1.name == name)),
      do: link(code(name), context_path(name)),
      else: "#{code(name)} (external)"
  end

  # --- a value, an entity ------------------------------------------------------------

  defp value_page(site, v) do
    [
      "# Value #{code(v.name)}#{label(v)}",
      "",
      link("Domain #{code(site.domain.name)}", "index.md"),
      "",
      facts([
        if(v.type, do: row(["Type: ", type_link(site, v.type)]), else: "A value with fields."),
        if(v.unit, do: "Unit: #{code(v.unit)}."),
        if(v.context, do: row(["Context: ", link(code(v.context), context_path(v.context))]))
      ]),
      if(v.fields != [], do: ["", "## Fields", "" | fields_table(site, v.fields)], else: []),
      invariants(v.invariants),
      used_by(site, v.name)
    ]
    |> Enum.reject(&is_nil/1)
  end

  defp invariants([]), do: []

  defp invariants(invariants) do
    [
      "",
      "## Invariants",
      "",
      "Dispatch holds every value of the type to each, and every example is a test.",
      for i <- invariants do
        [
          "",
          "### #{code(i.name)}",
          "",
          i.label,
          "",
          "Broken by: #{Enum.map_join(i.violated_by, ", ", &code(shown(&1)))}",
          "",
          "Kept by: #{Enum.map_join(i.satisfied_by, ", ", &code(shown(&1)))}",
          if(i.source, do: ["", "_Source: #{i.source}_"], else: [])
        ]
      end
    ]
  end

  # Every declaration with a field of the type, and every value or entity with one.
  defp used_by(site, name) do
    aliases =
      for v <- site.domain.values,
          mentions?(v.type, name),
          do: bullet(["value ", link(code(v.name), value_path(v.name))])

    section("Used by", aliases ++ holders(site, &mentions?(&1.type, name)), & &1)
  end

  # Every declaration, value and entity with a field `wanted` says yes to.
  defp holders(site, wanted) do
    in_domain =
      for(
        v <- site.domain.values,
        Enum.any?(v.fields, wanted),
        do: bullet(["value ", link(code(v.name), value_path(v.name))])
      ) ++
        for e <- site.domain.entities,
            Enum.any?(e.fields, wanted),
            do: bullet(["entity ", link(code(e.name), entity_path(e.name))])

    in_contracts =
      for model <- site.contracts,
          {key, declaration, fields} <- field_holders(model),
          Enum.any?(fields, wanted) do
        bullet([
          kind_word(key, declaration),
          " ",
          link(code(declaration.name), holder_path(model, key, declaration)),
          " of #{inspect(model.module)}"
        ])
      end

    in_domain ++ in_contracts
  end

  defp mentions?({:list, inner}, name), do: mentions?(inner, name)
  defp mentions?(type, name), do: type == name

  defp field_holders(model) do
    Enum.concat([
      for(u <- model.units, do: {:unit, u, u.state.fields}),
      for(c <- model.commands, do: {:commands, c, c.fields}),
      for(e <- model.events, do: {:events, e, e.fields}),
      for(pm <- model.process_managers, do: {:process_managers, pm, pm.state.fields}),
      for(r <- model.read_models, do: {:read_models, r, r.fields}),
      for(q <- model.queries, do: {:queries, q, q.params}),
      for(
        s <- model.domain_services,
        do: {:domain_services, s, Enum.flat_map(s.functions, &[&1.returns | &1.arguments])}
      )
    ])
  end

  defp holder_path(model, :unit, unit), do: unit_path(model, unit)
  defp holder_path(model, key, declaration), do: declaration_path(model, key, declaration.name)

  defp kind_word(:unit, unit), do: Atom.to_string(unit.kind)

  defp kind_word(key, _declaration) do
    {_, _, word} = List.keyfind(@kinds, key, 0)
    String.downcase(word)
  end

  defp entity_page(site, e) do
    [
      "# Entity #{code(e.name)} — #{e.label}",
      "",
      link("Domain #{code(site.domain.name)}", "index.md"),
      "",
      facts([
        row(["Context: ", link(code(e.context), context_path(e.context))]),
        "Identified by #{code(e.identified_by)}.",
        if(e.source, do: "_Source: #{e.source}_")
      ]),
      "",
      "## Fields",
      "",
      fields_table(site, e.fields),
      section("Referred to by", holders(site, &(Map.get(&1, :refers_to) == e.name)), & &1)
    ]
    |> Enum.reject(&is_nil/1)
  end

  # --- a context ---------------------------------------------------------------------

  defp context_page(site, c) do
    d = site.domain
    contracts = Enum.filter(site.contracts, &(&1.context == c.name))

    relations =
      for r <- d.relations,
          c.name in (r.between ++ [r.upstream, r.downstream]),
          do: relation(site, r)

    [
      "# Context #{code(c.name)} — #{c.label}",
      "",
      row([
        link("Domain #{code(d.name)}", "index.md"),
        " · subdomain #{code(c.subdomain)} · written in #{code(c.language || d.language)}"
      ]),
      if(c.source, do: ["", "_Source: #{c.source}_"], else: []),
      "",
      "## Contracts",
      "",
      case contracts do
        [] ->
          "_No contract._"

        _ ->
          for m <- contracts,
              do: bullet([link(code(inspect(m.module)), contract_path(m)), process_label(m)])
      end,
      section("Relations", relations, & &1),
      glossary(c)
    ]
  end

  defp process_label(%{process: %{label: label}}), do: " — #{label}"
  defp process_label(_model), do: ""

  defp glossary(%{terms: []}), do: ["", "## Glossary", "", "_No terms._"]

  defp glossary(c) do
    [
      "",
      "## Glossary",
      for t <- c.terms do
        [
          "",
          "### #{t.text}",
          "",
          t.definition,
          avoid(t.avoid),
          if(t.source, do: ["", "_Source: #{t.source}_"], else: []),
          for tr <- t.translations do
            ["", "_#{tr.language}_: **#{tr.text}** — #{tr.definition}", avoid(tr.avoid)]
          end
        ]
      end
    ]
  end

  defp avoid([]), do: []

  defp avoid(words) do
    for w <- words do
      if w.reason,
        do: ["", ~s|_Avoid "#{w.text}"._ #{w.reason}|],
        else: ["", ~s|_Avoid "#{w.text}"._|]
    end
  end

  # --- a contract --------------------------------------------------------------------

  defp contract_pages(site, model) do
    declarations =
      for({key, _, _} <- @kinds, d <- Map.fetch!(model, key), do: {key, d}) ++
        for u <- model.units, do: {:unit, u}

    [{contract_path(model), contract_page(site, model)}] ++
      for {key, d} <- declarations do
        {holder_path(model, key, d), declaration_page(site, model, key, d)}
      end
  end

  defp contract_page(site, model) do
    [
      "# Contract #{code(inspect(model.module))}",
      "",
      row([
        link("Domain #{code(site.domain.name)}", "index.md"),
        " · context ",
        link(code(model.context), context_path(model.context)),
        " · version #{code(model.version)}"
      ]),
      process_section(site, model),
      section("Units", model.units, &declaration_bullet(model, :unit, &1)),
      for {key, _dir, word} <- @kinds, key not in [:commands, :events] do
        section(plural(word), Map.fetch!(model, key), &declaration_bullet(model, key, &1))
      end,
      consumes_section(site, model),
      section("Published", model.publishes, fn p ->
        bullet([
          "#{code(p.name)}, published as #{code(p.as)}, from ",
          event_link(site, model, p.from)
        ])
      end),
      scenarios(model, model.scenarios)
    ]
  end

  defp plural("Policy"), do: "Policies"
  defp plural("Query"), do: "Queries"
  defp plural(word), do: word <> "s"

  defp declaration_bullet(model, key, d),
    do: bullet([link(code(d.name), holder_path(model, key, d)), label(d)])

  defp process_section(_site, %{process: nil}), do: []

  defp process_section(site, %{process: p} = model) do
    elsewhere = for i <- p.includes, i.stage == nil, do: include(site, model, i)

    [
      "",
      "## Process #{code(p.name)} — #{p.label}",
      "",
      facts([
        "Runs are told by #{Enum.map_join(p.correlate, ", ", &code/1)}.",
        if(p.accountable, do: "Accountable: #{code(p.accountable)}."),
        if(p.deadline, do: "Deadline: #{duration(p.deadline)}."),
        if(p.cadence, do: "Cadence: every #{duration(p.cadence)}.")
      ]),
      stages(site, model, p),
      section("Included from other contracts", elsewhere, & &1),
      section("Promises", p.promises, &promise(site, model, &1))
    ]
  end

  # A stage's events: the unit's own in it, then those `include` places there.
  defp stages(site, model, p) do
    section("Stages", p.stages, fn stage ->
      events =
        for(e <- model.events, e.stage == stage.name, do: event_link(site, model, e.name)) ++
          for i <- p.includes, i.stage == stage.name, do: include(site, model, i)

      bullet(["#{code(stage.name)}#{label(stage)}: " | joined(events)])
    end)
  end

  defp include(site, model, i),
    do: [event_link(site, model, i.event), if(i.terminal, do: " (ends a run)")]

  defp promise(site, model, p) do
    events = &joined(Enum.map(List.wrap(&1), fn e -> event_link(site, model, e) end))

    bullet([
      "#{code(p.name)}: after ",
      events.(p.from),
      ", eventually ",
      events.(p.eventually),
      if(Map.get(p, :within), do: " within #{duration(p.within)}"),
      if(Map.get(p, :or_else), do: [", or else ", events.(p.or_else)]),
      if(Map.get(p, :unverified), do: " (unverified)")
    ])
  end

  # `%{amount: 3, unit: :day}` as "3 days", and what the owner has not confirmed.
  defp duration(%{amount: amount, unit: unit} = d) do
    word = if amount == 1, do: "#{unit}", else: "#{unit}s"
    "#{amount} #{word}" <> if(Map.get(d, :unverified), do: " (unverified)", else: "")
  end

  defp duration({amount, unit}) when is_integer(amount),
    do: duration(%{amount: amount, unit: unit})

  defp duration(other), do: code(shown(other))

  defp consumes_section(site, model) do
    section("Consumed", model.consumes, fn
      # Each event linked to the sibling's page, under the name it has here.
      %{kind: :contract, from: from, events: events} = c ->
        sibling = Enum.find(site.contracts, &(&1.module == from))

        target =
          if sibling,
            do: link(code(inspect(from)), contract_path(sibling)),
            else: code(inspect(from))

        renames = Map.get(c, :renames, %{})

        consumed =
          for e <- events do
            name =
              if sibling, do: link(code(e), declaration_path(sibling, :events, e)), else: code(e)

            as = Map.get(renames, e)
            [name, if(as && as != e, do: " as #{code(as)}")]
          end

        bullet([target, ": " | joined(consumed)])

      %{kind: :published} = c ->
        "- #{code(c.from)}, received as #{code(c.as)}"
    end)
  end

  defp scenarios(_model, []), do: []

  defp scenarios(model, scenarios) do
    [
      "",
      "## Scenarios",
      # The description, then what happens, as two paragraphs of one item.
      for s <- scenarios do
        ["", "- #{s.description}", "", "  " <> scenario_line(model, s)]
      end
    ]
  end

  defp scenario_line(_model, s) do
    given = Enum.map(s.given, &code(&1.event))
    trigger = "#{s.trigger.kind} #{code(s.trigger.name)}"

    # What a process manager's scenario says of its timers and its end, too.
    outcome =
      [
        if(s.rejected, do: "rejected on #{code(s.rejected)}"),
        if(s.expect != [], do: "expects #{Enum.map_join(s.expect, ", ", &code(&1.event))}"),
        if(s.issues != [], do: "issues #{Enum.map_join(s.issues, ", ", &code(&1.command))}"),
        if(Map.get(s, :sets, []) != [], do: "sets #{Enum.map_join(s.sets, ", ", &code/1)}"),
        if(Map.get(s, :cancels, []) != [],
          do: "cancels #{Enum.map_join(s.cancels, ", ", &code/1)}"
        ),
        if(Map.get(s, :ended), do: "ends the run"),
        if(Map.has_key?(s, :answers), do: "answers #{length(List.wrap(s.answers))} row(s)")
      ]
      |> Enum.reject(&is_nil/1)
      |> Enum.join(", ")
      |> blank("as declared")

    given = if given == [], do: "", else: "given #{Enum.join(given, ", ")}; "
    "#{given}#{trigger}; #{outcome}"
  end

  # --- one declaration -----------------------------------------------------------------

  defp declaration_page(site, model, key, d) do
    [
      "# #{title(key, d)} #{code(d.name)}#{label(d)}",
      "",
      row([
        "Contract ",
        link(code(inspect(model.module)), contract_path(model)),
        " · context ",
        link(code(model.context), context_path(model.context))
      ]),
      if(Map.get(d, :source), do: ["", "_Source: #{d.source}_"], else: []),
      body(site, model, key, d),
      scenarios(model, Enum.filter(model.scenarios, &about?(&1, key, d)))
    ]
  end

  defp title(:unit, unit), do: String.capitalize(Atom.to_string(unit.kind))

  defp title(key, _d) do
    {_, _, word} = List.keyfind(@kinds, key, 0)
    word
  end

  defp about?(%{target: %{kind: kind, name: name}}, :unit, %{kind: kind, name: name}), do: true
  defp about?(%{trigger: %{kind: :command, name: name}}, :commands, %{name: name}), do: true

  defp about?(%{target: %{kind: kind, name: name}}, key, %{name: name})
       when {kind, key} in [
              policy: :policies,
              process_manager: :process_managers,
              query: :queries
            ],
       do: true

  defp about?(_scenario, _key, _d), do: false

  defp body(site, model, :unit, u) do
    commands = Enum.filter(model.commands, &(&1.unit == u.name))
    events = Enum.filter(model.events, &(&1.unit == u.name))

    [
      facts(["Identity: #{Enum.map_join(u.identity, ", ", &code/1)}."]),
      section("Consults", u.consults, &consults(site, model, &1)),
      section("Invariants", u.invariants, fn i ->
        rejecting = for c <- commands, i.name in c.rejects, do: command_link(model, c.name)
        bullet(["#{code(i.name)} — #{i.label} · rejected by " | joined(rejecting)])
      end),
      ["", "## State", "" | fields_table(site, u.state.fields)],
      section("Commands", commands, &declaration_bullet(model, :commands, &1)),
      section("Events", events, &declaration_bullet(model, :events, &1))
    ]
  end

  defp body(site, model, :commands, c) do
    unit = Enum.find(model.units, &(&1.name == c.unit))

    [
      facts([
        row([
          "#{String.capitalize(Atom.to_string(unit.kind))} ",
          link(code(unit.name), unit_path(model, unit))
        ]),
        "Issued by: #{Enum.map_join(List.wrap(c.by), ", ", &code/1) |> blank("no actor")}.",
        row(["Emits: " | joined(Enum.map(c.emits, &event_link(site, model, &1)))]),
        if(c.rejects != [], do: "Rejects on: #{Enum.map_join(c.rejects, ", ", &code/1)}."),
        if(Map.get(c, :creates),
          do: "Creates its #{unit.kind}, whose identity the library gives."
        )
      ]),
      section("Constraints", Map.get(c, :constraints, []), &"- #{code(&1.name)} — #{&1.label}"),
      issued_by_reactions(model, c),
      ["", "## Fields", "" | fields_table(site, c.fields)]
    ]
  end

  defp body(site, model, :events, e) do
    unit = Enum.find(model.units, &(&1.name == e.unit))
    emitted = for c <- model.commands, e.name in c.emits, do: command_link(model, c.name)

    [
      facts([
        row([
          "#{String.capitalize(Atom.to_string(unit.kind))} ",
          link(code(unit.name), unit_path(model, unit))
        ]),
        if(e.type, do: "Stored as #{code(e.type)}."),
        row(["Emitted by: " | joined(emitted)]),
        if(e.recorded_by != [],
          do: "Recorded by: #{Enum.map_join(e.recorded_by, ", ", &code/1)}."
        ),
        if(e.stage, do: "Stage: #{code(e.stage)}."),
        if(e.terminal, do: "Ends a run.")
      ]),
      readers(site, model, e),
      ["", "## Fields", "" | fields_table(site, e.fields)]
    ]
  end

  defp body(site, model, :policies, p) do
    facts([
      row(["Handles: " | joined(Enum.map(List.wrap(p.handles), &event_link(site, model, &1)))]),
      row(["Issues: " | joined(Enum.map(List.wrap(p.issues), &command_link(model, &1)))]),
      "Delivered #{code(p.delivery)}."
    ])
  end

  defp body(site, model, :effects, e) do
    facts([
      row(["Handles: " | joined(Enum.map(List.wrap(e.handles), &event_link(site, model, &1)))]),
      if(e.calls not in [nil, []],
        do: "Calls: #{Enum.map_join(List.wrap(e.calls), ", ", &code/1)}."
      ),
      "Delivered #{code(e.delivery)}."
    ])
  end

  defp body(site, model, :process_managers, pm) do
    # What a reaction does: the commands it issues, the timers it sets and cancels.
    reaction = fn r ->
      issues = Enum.map(Map.get(r, :issues, []), &command_link(model, &1))

      timers =
        for {word, key} <- [sets: :sets, cancels: :cancels],
            t <- List.wrap(Map.get(r, key)),
            do: "#{word} timer #{code(t)}"

      # `on` may name one of the manager's own timers, which fires, rather than an event.
      trigger =
        if Enum.any?(pm.timers, &(&1.name == r.event)),
          do: "timer #{code(r.event)}",
          else: event_link(site, model, r.event)

      bullet([trigger, " → " | joined(issues ++ timers)])
    end

    [
      facts(["Runs are told by #{Enum.map_join(pm.correlate, ", ", &code/1)}."]),
      section("Starts on", pm.starts_on, reaction),
      section("Reacts to", pm.on, reaction),
      section("Timers", pm.timers, fn t ->
        issues = Enum.map(t.issues, &command_link(model, &1))
        bullet(["#{code(t.name)} → " | joined(issues)])
      end),
      section("Ends on", pm.ends_on, &bullet([event_link(site, model, &1)])),
      ["", "## State", "" | fields_table(site, pm.state.fields)]
    ]
  end

  defp body(site, model, :read_models, r) do
    queries =
      for q <- model.queries, q.reads == r.name, do: declaration_bullet(model, :queries, q)

    [
      facts([
        row([
          "Projects: " | joined(Enum.map(List.wrap(r.projects), &event_link(site, model, &1)))
        ]),
        "Delivered #{code(r.delivery)}."
      ]),
      section("Queries", queries, & &1),
      ["", "## Fields", "" | fields_table(site, r.fields)]
    ]
  end

  defp body(site, model, :queries, q) do
    read_model = Enum.find(model.read_models, &(&1.name == q.reads))

    [
      facts([
        row([
          "Reads: ",
          link(code(q.reads), declaration_path(model, :read_models, read_model.name))
        ]),
        "Asked by: #{Enum.map_join(List.wrap(q.by), ", ", &code/1) |> blank("no actor")}.",
        "Returns #{if q.returns == :one, do: "one row or none", else: "rows"}.",
        if(q.scope, do: "Narrowed by #{code(q.scope)}.")
      ]),
      section("Constraints", Map.get(q, :constraints, []), &"- #{code(&1.name)} — #{&1.label}"),
      ["", "## Parameters", "" | fields_table(site, q.params)]
    ]
  end

  defp body(site, _model, :domain_services, s) do
    for f <- s.functions do
      arguments = for a <- f.arguments, do: [code(a.name), " ", type_link(site, a.type)]

      [
        "",
        "## #{code(f.name)} — #{f.label}",
        "",
        row(["Takes " | joined(arguments)]),
        "",
        row([
          "Returns ",
          type_link(site, f.returns.type),
          if(f.returns.optional, do: ", or nothing", else: "")
        ]),
        for r <- f.rules do
          [
            "",
            "- **#{code(r.name)}** — #{r.label}",
            for(
              {args, result} <- r.examples,
              do:
                "  - `#{f.name}(#{Enum.map_join(args, ", ", &shown/1)})` returns `#{shown(result)}`"
            )
          ]
        end
      ]
    end
  end

  # Facts about a declaration, each a paragraph of its own.
  defp facts(lines), do: lines |> Enum.reject(&is_nil/1) |> Enum.flat_map(&["", &1])

  # An example as written, the same on every machine: `inspect/1` prints a map's keys
  # in the order of their atoms, which depends on when each atom was made, so a page
  # would differ between two builds and `--check` would fail on one of them.
  defp shown(%{__struct__: _} = struct), do: inspect(struct)

  defp shown(%{} = map) do
    pairs =
      map
      |> Enum.sort_by(fn {key, _} -> to_string(key) end)
      |> Enum.map_join(", ", fn
        {key, value} when is_atom(key) -> "#{key}: #{shown(value)}"
        {key, value} -> "#{inspect(key)} => #{shown(value)}"
      end)

    "%{#{pairs}}"
  end

  defp shown(list) when is_list(list), do: "[#{Enum.map_join(list, ", ", &shown/1)}]"

  defp shown(tuple) when is_tuple(tuple),
    do: "{#{tuple |> Tuple.to_list() |> Enum.map_join(", ", &shown/1)}}"

  defp shown(term), do: inspect(term)

  defp blank("", word), do: word
  defp blank(text, _word), do: text

  defp consults(site, model, c) do
    how =
      cond do
        Map.get(c, :match, []) != [] -> " by #{Enum.map_join(c.match, ", ", &code/1)}"
        is_binary(Map.get(c, :where)) -> " where #{c.where}"
        true -> ""
      end

    bullet([event_link(site, model, c.event), how])
  end

  # The reactions of this contract that issue the command.
  defp issued_by_reactions(model, c) do
    policies =
      for p <- model.policies,
          c.name in List.wrap(p.issues),
          do: bullet(["policy ", declaration_bullet_link(model, :policies, p)])

    managers =
      for pm <- model.process_managers,
          c.name in Enum.flat_map(pm.starts_on ++ pm.on ++ pm.timers, &Map.get(&1, :issues, [])),
          do: bullet(["process manager ", declaration_bullet_link(model, :process_managers, pm)])

    section("Issued by reactions", policies ++ managers, & &1)
  end

  defp declaration_bullet_link(model, key, d), do: link(code(d.name), holder_path(model, key, d))

  # Who reads the event: this contract's consumers, and the contracts consuming it.
  defp readers(site, model, e) do
    own =
      Enum.concat([
        for(p <- model.policies, e.name in List.wrap(p.handles), do: {"policy", :policies, p}),
        for(x <- model.effects, e.name in List.wrap(x.handles), do: {"effect", :effects, x}),
        for(
          pm <- model.process_managers,
          e.name in (Enum.map(pm.starts_on ++ pm.on, & &1.event) ++ pm.ends_on),
          do: {"process manager", :process_managers, pm}
        ),
        for(
          r <- model.read_models,
          e.name in List.wrap(r.projects),
          do: {"read model", :read_models, r}
        )
      ])
      |> Enum.map(fn {word, key, d} ->
        bullet([word, " ", declaration_bullet_link(model, key, d)])
      end)

    others =
      for other <- site.contracts,
          other.module != model.module,
          %{kind: :contract, from: from, events: events} <- other.consumes,
          from == model.module,
          e.name in events do
        bullet(["contract ", link(code(inspect(other.module)), contract_path(other))])
      end

    section("Read by", own ++ others, & &1)
  end
end
