defmodule EhOsContract.Pages do
  # A domain and its contracts as Markdown pages, one per element, linked to each
  # other (ESDM's `documentation`; plan EL3). `mix eh_os_contract.pages --output <dir>`
  # writes them.
  #
  #     index.md                                    the domain, with its tree
  #     values/money.md                             a value: its type, invariants, examples
  #     entities/<name>.md                          an entity
  #     settlement/index.md                         a context: glossary, relations, contracts
  #     settlement/visit_settlement/index.md        a contract: its declarations
  #     settlement/visit_settlement/commands/record_payment.md
  #     settlement/visit_settlement/events/payment_recorded.md
  #     settlement/visit_settlement/aggregates/visit_settlement.md
  #     …/dcbs, policies, effects, process_managers, read_models, queries, domain_services
  #     processes/clinical_visit.md                 a process module, by its id after the
  #                                                 domain's name, a dot a directory
  #     graph/rehmed.settlement.json  a contract's graph.v1 document, by its id
  #     graph/process/rehmed.clinical_visit.json    a process module's, by its id
  #
  # A process module's document has a directory of its own, as its API path has
  # (`/graph/process/<id>`): a process module may share its `id:` with a contract
  # (plan DD, P2e (#220)).
  #
  # A contract's directory is its module's last segment, underscored. Each kind has a
  # directory of its own, since a contract's namespaces overlap: a read model may share
  # a unit's name. Every link is relative, so the pages read the same wherever the
  # directory goes — a repository, ExDoc's `extras`, a file browser.
  #
  # The words around the model are the library's, in English; labels, terms,
  # definitions and scenario descriptions are the client's, printed as declared.
  # Everything comes in declaration order, as every reader of the model prints (v2 §9).
  # Each page starts with `marker/2` of its domain, which is how the task tells the
  # pages it wrote for that domain from files it must leave alone — a person's, or
  # another domain's pages in the same directory.
  #
  # **The owner's view** (`audience: :owner`; plan DD, L4 (#326)) is the same tree for
  # the business owner: each declaration by its label, and nothing of the engineering —
  # no module, version or stored type, no delivery, idempotency or correlation, no
  # names or types of fields, and no graph documents. `site.audience` says which, and
  # the helpers that name a declaration or print a fact of the code ask it.
  @moduledoc false

  alias EhOsContract.Model
  alias EhOsContract.Contract.Doc

  # A contract's declarations with a page of their own: the model's key, the
  # directory, and the word for one.
  @kinds [
    {:commands, "commands", "Command"},
    {:events, "events", "Event"},
    {:policies, "policies", "Policy"},
    {:effects, "effects", "Effect"},
    {:process_managers, "process_managers", "Process manager"},
    {:read_models, "read_models", "Read model"},
    {:queries, "queries", "Query"},
    {:domain_services, "domain_services", "Domain service"}
  ]

  @doc """
  The first line of every page of the domain named `name` for `audience`, which tells a
  page generated for it from any other file, and the owner's pages from the engineer's.
  """
  @spec marker(atom(), :engineering | :owner) :: String.t()
  def marker(name, audience \\ :engineering)

  def marker(name, :engineering),
    do:
      "<!-- Generated by mix eh_os_contract.pages for domain #{name}. Edits are overwritten. -->"

  def marker(name, :owner),
    do:
      "<!-- Generated by mix eh_os_contract.pages --audience owner for domain #{name}. " <>
        "Edits are overwritten. -->"

  @doc """
  The pages of `domain`, a domain module or its model, and of `modules`, the v2
  contract modules and process modules naming it, or their models, as
  `%{relative path => Markdown}`, and beside them each one's `graph.v1` document: a
  contract's as `graph/<contract id>.json`, a process module's as
  `graph/process/<process id>.json`. Modules naming another domain are left out.
  Raises when two contracts of one context would share a directory, when two elements
  would share a page, and when a name is not snake_case, since pages are named after
  names.

  With `audience: :owner` the pages are for the business owner: the same tree, each
  declaration by its label, without the code's names, types and delivery, and without
  the graph documents.
  """
  @spec render(module() | map(), [module() | map()], keyword()) :: %{String.t() => String.t()}
  def render(domain, modules, opts \\ []) do
    domain = Model.fetch(domain)
    audience = Keyword.get(opts, :audience, :engineering)

    %{contract: contracts, process: processes} =
      modules
      |> Enum.map(&Model.fetch/1)
      |> Enum.filter(&(&1.domain == domain.module))
      |> Enum.group_by(& &1.kind)
      |> then(&Map.merge(%{contract: [], process: []}, &1))

    distinct!(contracts)
    # What every reference name resolves to, once for all pages (plan DD, L3 (#286)).
    referents = EhOsContract.References.index(domain, contracts)
    # Plan DD, P2e (#220): each process module with the events it includes, resolved.
    processes = for p <- processes, do: {p, Model.process_events(p)}

    site = %{
      domain: domain,
      contracts: contracts,
      processes: processes,
      referents: referents,
      audience: audience
    }

    [{"index.md", domain_page(site)}]
    |> Enum.concat(for v <- domain.values, do: {value_path(v.name), value_page(site, v)})
    |> Enum.concat(for e <- domain.entities, do: {entity_path(e.name), entity_page(site, e)})
    |> Enum.concat(for c <- domain.contexts, do: {context_path(c.name), context_page(site, c)})
    |> Enum.concat(Enum.flat_map(contracts, &contract_pages(site, &1)))
    |> Enum.concat(
      for {p, events} <- processes, do: {process_path!(p), process_page(site, p, events)}
    )
    |> paths!()
    |> Map.new(fn {path, lines} -> {path, page(marker(domain.name, audience), path, lines)} end)
    |> Map.merge(graphs(site))
  end

  # The owner's pages have no graph documents: they are the engineer's.
  defp graphs(%{audience: :owner}), do: %{}

  defp graphs(site) do
    models = site.contracts ++ Enum.map(site.processes, &elem(&1, 0))
    Map.new(models, &{graph_path!(&1), graph(&1)})
  end

  # A contract's or a process module's `graph.v1` document beside its pages (plan E13a,
  # the user's decision (b) on the model pages): the bytes the API serves, indented,
  # without the log.
  defp graph(%{kind: :process} = model), do: encoded(EhOsContract.Graph.Document.process(model))
  defp graph(model), do: encoded(EhOsContract.Graph.Document.contract(model))

  defp encoded(document),
    do: EhOsContract.Graph.Document.encode(document, pretty: true) <> "\n"

  @doc """
  Whether `text`, the content of a file at `path` under the pages' directory, is a
  contract's or a process module's `graph.v1` document these pages write for `domain`
  — the one kind of file among them that cannot start with `marker/1`.
  """
  @spec graph?(String.t(), String.t(), module()) :: boolean()
  def graph?(path, text, domain) do
    name = inspect(domain)

    # Only at the path these pages give that contract or process module: a copy of the
    # document a person saved elsewhere under `graph/` is theirs.
    case Jason.decode(text) do
      {:ok, %{"schema" => "eh_os_contract.graph.v1", "kind" => kind, "domain" => ^name} = doc}
      when kind in ["contract", "process"] ->
        id = doc[kind]
        kind = if kind == "process", do: :process, else: :contract
        is_binary(id) and graph_id?(id) and path == graph_path(%{kind: kind, id: id})

      _other ->
        false
    end
  end

  # A path is made of names. Every name of a domain and a contract is snake_case (D1,
  # N1), but a model can be built by hand, and one written `:"../x"` would write
  # outside the directory, one with a space would break every link to it. Two elements
  # of one path, `context :values` and `value :index`, both `values/index.md`, would
  # leave one of them without a page.
  defp paths!(pages) do
    for {path, _lines} <- pages,
        segment <- path |> String.trim_trailing(".md") |> Path.split(),
        not EhOsContract.DslRules.snake_case?(segment) do
      raise ArgumentError,
            "the page #{inspect(path)} would be named after #{inspect(segment)}; a page is " <>
              "named after a snake_case name"
    end

    for path <- pages |> Enum.map(&elem(&1, 0)) |> EhOsContract.DslRules.duplicates(& &1) do
      raise ArgumentError, "two elements would have the page #{path}; rename one of them"
    end

    pages
  end

  defp distinct!(contracts) do
    for {{context, slug}, [first, second | _]} <-
          Enum.group_by(contracts, &{&1.context, slug(&1)}, & &1.module) do
      raise ArgumentError,
            "#{inspect(first)} and #{inspect(second)} would share the directory " <>
              "#{context}/#{slug}; a context's contracts have pages under the last segment of " <>
              "their module's name"
    end
  end

  # A page is its lines with the links resolved against where it is.
  defp page(marker, path, lines) do
    body =
      lines
      |> List.flatten()
      |> Enum.reject(&is_nil/1)
      |> Enum.map(&line(&1, path))
      |> Enum.join("\n")
      |> String.replace(~r/\n{3,}/, "\n\n")
      |> String.trim_trailing()

    Enum.join([marker, "", body, ""], "\n")
  end

  # A line is a string, a link, or a row of both.
  defp line({:row, parts}, path),
    do: parts |> List.flatten() |> Enum.reject(&is_nil/1) |> Enum.map_join(&line(&1, path))

  defp line({:link, text, to}, path), do: "[#{text}](#{relative(path, to)})"
  defp line(text, _path) when is_binary(text), do: text

  # --- paths and links ------------------------------------------------------------

  defp value_path(name), do: "values/#{name}.md"
  defp entity_path(name), do: "entities/#{name}.md"
  defp context_path(name), do: "#{name}/index.md"
  defp contract_dir(model), do: "#{model.context}/#{slug(model)}"

  # A contract's document is named after its `id:`, which D11 holds to dotted names; a
  # model built by hand is not held to it, and an id such as `"../x"` would write
  # outside the directory, as `paths!/1` says of a page. A process module's `id:` is
  # held to the same form.
  defp graph_path!(model) do
    id!(model)
    graph_path(model)
  end

  defp id!(model) do
    unless graph_id?(model.id) do
      what = if model.kind == :process, do: "a process module's", else: "a contract's"

      raise ArgumentError,
            "the graph document of #{inspect(model.module)} would be named after " <>
              "#{inspect(model.id)}; #{what} document is named after its id:, a dotted name"
    end
  end

  defp graph_path(%{kind: :process, id: id}), do: "graph/process/#{id}.json"
  defp graph_path(model), do: "graph/#{model.id}.json"

  # A process module's page is named after its `id:` without the domain's name, each
  # further segment a directory: `rehmed.clinical_visit` is `processes/clinical_visit.md`.
  # Two process modules of one domain cannot share it, since they cannot share an id.
  defp process_path!(model) do
    id!(model)
    process_path(model)
  end

  defp process_path(model) do
    [_namespace | rest] = String.split(model.id, ".")
    "processes/#{Enum.join(rest, "/")}.md"
  end

  defp graph_id?(id),
    do: EhOsContract.Contract.Rules.Boundaries.id_form(%{value: id, at: nil}, "contract") == []

  defp contract_path(model), do: "#{contract_dir(model)}/index.md"
  defp slug(model), do: model.module |> Module.split() |> List.last() |> Macro.underscore()

  defp declaration_path(model, key, name) do
    {_, dir, _} = List.keyfind(@kinds, key, 0) || {key, unit_dir(key), nil}
    "#{contract_dir(model)}/#{dir}/#{name}.md"
  end

  defp unit_dir(:aggregate), do: "aggregates"
  defp unit_dir(:dcb), do: "dcbs"

  defp unit_path(model, unit), do: declaration_path(model, unit.kind, unit.name)

  # `to`, from the directory of `from`.
  defp relative(from, to), do: Path.relative_to(to, Path.dirname(from), force: true)

  defp link(text, to), do: {:link, text, to}
  # A code span; one holding a backtick is fenced by two, as CommonMark reads it.
  defp code(name) do
    text = to_string(name)
    if String.contains?(text, "`"), do: "`` #{text} ``", else: "`#{text}`"
  end

  # The client's text in a table cell: a `|` would end the cell, a line break the row.
  defp cell(nil), do: ""
  defp cell(text), do: text |> String.replace("|", "\\|") |> String.replace(~r/\s*\n\s*/, " ")

  # --- the audience ----------------------------------------------------------------

  # A declaration as a page names it: its name in the code, or for the owner its label,
  # its name only where it has none (`owner-view-without-label`).
  defp named(%{audience: :owner}, %{label: label}) when is_binary(label), do: label
  defp named(_site, d), do: code(d.name)

  # A declaration in a list: its name and its label, or for the owner the label alone.
  defp labelled(%{audience: :owner} = site, d), do: named(site, d)
  defp labelled(_site, d), do: code(d.name) <> label(d)

  # A link to a declaration's page: its name, with its label after it, or for the owner
  # the label alone.
  defp linked(%{audience: :owner} = site, d, path), do: [link(named(site, d), path)]
  defp linked(_site, d, path), do: [link(code(d.name), path), label(d)]

  # A fact of the code, which the owner's pages leave out.
  defp code_fact(%{audience: :owner}, _fact), do: nil
  defp code_fact(_site, fact), do: fact

  # An actor, a context or an external system named in a declaration, by its name in
  # the code or the owner's label.
  defp actor_name(site, name), do: domain_name(site, site.domain.actors, name)
  defp context_name(site, name), do: domain_name(site, site.domain.contexts, name)
  defp external_name(site, name), do: domain_name(site, site.domain.externals, name)

  defp domain_name(%{audience: :owner} = site, declarations, name) do
    case Enum.find(declarations, &(&1.name == name)) do
      nil -> code(name)
      d -> named(site, d)
    end
  end

  defp domain_name(_site, _declarations, name), do: code(name)

  # A contract by its module, or for the owner by its context's label, with its units'
  # where the context has more than one contract.
  defp contract_name(%{audience: :owner} = site, model) do
    context = context_name(site, model.context)

    cond do
      Enum.count(site.contracts, &(&1.context == model.context)) == 1 -> context
      model.units == [] -> "#{context}: #{slug(model) |> String.replace("_", " ")}"
      true -> "#{context}: #{Enum.map_join(model.units, ", ", &named(site, &1))}"
    end
  end

  defp contract_name(_site, model), do: code(inspect(model.module))

  # An event as the contract names it: its own page, a sibling's, or plain text for
  # one received from another application.
  defp event_link(site, model, name) do
    case Enum.find(model.events, &(&1.name == name)) do
      %{} = event ->
        link(named(site, event), declaration_path(model, :events, name))

      nil ->
        with {:contract, from, original} <- Model.consumed(model, name),
             %{} = sibling <- Enum.find(site.contracts, &(&1.module == from)) do
          link(
            sibling_event(site, sibling, name, original),
            declaration_path(sibling, :events, original)
          )
        else
          _ -> received(site, name)
        end
    end
  end

  # An event another application published, which has no label here.
  defp received(%{audience: :owner}, _name), do: "an event from another application"
  defp received(_site, name), do: "#{code(name)} (received)"

  defp sibling_event(%{audience: :owner} = site, sibling, name, original) do
    case Enum.find(sibling.events, &(&1.name == original)) do
      nil -> code(name)
      event -> named(site, event)
    end
  end

  defp sibling_event(_site, sibling, name, _original),
    do: "#{code(name)} of #{inspect(sibling.module)}"

  defp consumed_event(%{audience: :owner} = site, sibling, e),
    do: sibling_event(site, sibling, e, e)

  defp consumed_event(_site, _sibling, e), do: code(e)

  defp command_link(site, model, name) do
    command = Enum.find(model.commands, &(&1.name == name)) || %{name: name}
    link(named(site, command), declaration_path(model, :commands, name))
  end

  defp joined([]), do: ["—"]

  defp joined(items) do
    Enum.intersperse(items, ", ")
  end

  # --- fields ----------------------------------------------------------------------

  # A section of fields under `title`. The owner's has the labelled ones, and is left
  # out where there are none.
  defp fields_section(%{audience: :owner} = site, title, fields) do
    case for(%{label: label} = f <- fields, is_binary(label), do: f) do
      [] -> []
      labelled -> ["", "## #{title}", "" | fields_table(site, labelled)]
    end
  end

  defp fields_section(site, title, fields),
    do: ["", "## #{title}", "" | fields_table(site, fields)]

  defp fields_table(_site, []), do: ["_No fields._"]

  # The owner reads a field by its label, and one without a label is the code's.
  defp fields_table(%{audience: :owner}, fields) do
    ["| Field | |", "| --- | --- |"] ++
      for(f <- fields, do: "| #{cell(f.label)} | #{owner_notes(f)} |")
  end

  defp fields_table(site, fields) do
    rows =
      for f <- fields do
        [
          "| ",
          code(f.name),
          " | ",
          type(site, f),
          " | ",
          cell(Map.get(f, :label)),
          " | ",
          notes(f),
          " |"
        ]
      end

    ["| Field | Type | Label | |", "| --- | --- | --- | --- |" | Enum.map(rows, &row/1)]
  end

  # A row of a table with links in it, joined when the page resolves them.
  defp row(parts), do: {:row, parts}

  defp type(site, %{refers_to: name, type: {:list, inner}}) when name != nil,
    do: ["list of ", code(inspect(inner)), " of ", reference_link(site, name)]

  defp type(site, %{refers_to: name, type: type}) when name != nil,
    do: [code(inspect(type)), " of ", reference_link(site, name)]

  defp type(site, %{type: type}), do: type_link(site, type)

  defp type_link(site, {:list, inner}), do: ["list of ", type_link(site, inner)]

  defp type_link(site, name) when is_atom(name) do
    if Enum.any?(site.domain.values, &(&1.name == name)),
      do: link(code(name), value_path(name)),
      else: code(inspect(name))
  end

  defp type_link(_site, type), do: code(inspect(type))

  # What a field identifies: an entity's page, or a unit's (plan DD, L3 (#286)).
  defp reference_link(site, name) do
    case Map.get(site.referents, name) do
      {:entity, ^name} ->
        link(code(name), entity_path(name))

      {:unit, model, ^name} ->
        unit = Enum.find(model.units, &(&1.name == name))
        link(code(name), unit_path(model, unit))

      nil ->
        code(name)
    end
  end

  # Whether a field refers to `referent`, as the reference resolves.
  defp refers_to?(site, field, referent) do
    name = Map.get(field, :refers_to)
    name != nil and Map.get(site.referents, name) == referent
  end

  defp owner_notes(field) do
    [
      if(Map.get(field, :optional), do: "optional"),
      if(Map.get(field, :personal), do: "personal data")
    ]
    |> Enum.reject(&is_nil/1)
    |> Enum.join(", ")
  end

  defp notes(field) do
    [
      if(Map.get(field, :optional), do: "optional"),
      if(p = Map.get(field, :personal), do: "personal to #{code(p)}"),
      if(s = Map.get(field, :subject), do: "identifies a #{code(s)}"),
      if(i = Map.get(field, :issued_by), do: "issued by #{code(i)}"),
      if(Map.get(field, :supplied_by) == :host, do: "supplied by the host")
    ]
    |> Enum.reject(&is_nil/1)
    |> Enum.join(", ")
  end

  # --- the domain ------------------------------------------------------------------

  defp domain_page(site) do
    d = site.domain
    tree = EhOsContract.View.render(d, site.contracts ++ Enum.map(site.processes, &elem(&1, 0)))

    [
      "# Domain #{if site.audience == :owner, do: d.name, else: code(d.name)}",
      code_fact(site, ["", "Written in #{code(d.language)}. Version #{code(d.version)}."]),
      "",
      "## Contexts",
      "",
      for c <- d.contexts do
        subdomain = Enum.find(d.subdomains, &(&1.name == c.subdomain))
        kind = if subdomain, do: "#{subdomain.type} ", else: ""

        case site.audience do
          :owner ->
            bullet([
              link(c.label, context_path(c.name)),
              " · #{kind}subdomain #{if subdomain, do: subdomain.label, else: c.subdomain}"
            ])

          :engineering ->
            bullet([
              link(code(c.name), context_path(c.name)),
              " — #{c.label} · #{kind}subdomain #{code(c.subdomain)}"
            ])
        end
      end,
      section("Processes", site.processes, fn {p, _events} ->
        if site.audience == :owner,
          do: bullet([link(p.label, process_path(p))]),
          else: bullet([link(code(p.id), process_path(p)), " — #{p.label}"])
      end),
      section("Subdomains", d.subdomains, &"- #{labelled(site, &1)} · #{&1.type}"),
      section("Values", d.values, &bullet(linked(site, &1, value_path(&1.name)))),
      section("Entities", d.entities, &bullet(linked(site, &1, entity_path(&1.name)))),
      section("Actors", d.actors, &actor(site, &1)),
      section(
        "Subjects of personal data",
        d.subjects,
        &"- #{labelled(site, &1)}#{source_note(&1)}"
      ),
      section("External systems", d.externals, &external(site, &1)),
      section("Relations between contexts", d.relations, &relation(site, &1)),
      code_fact(site, ["", "## Tree", "", "```", tree, "```"])
    ]
  end

  defp bullet(parts), do: row(["- " | List.wrap(parts)])

  defp label(%{label: label}) when is_binary(label), do: " — #{label}"
  defp label(_), do: ""

  defp section(_title, [], _fun), do: []
  defp section(title, items, fun), do: ["", "## #{title}", "" | Enum.map(items, fun)]

  defp actor(site, a) do
    extra =
      [
        if(a.backed_by, do: "backed by #{external_name(site, a.backed_by)}"),
        if(a.context, do: "context #{context_name(site, a.context)}"),
        code_fact(site, if(a.scope != [], do: "scope #{Enum.map_join(a.scope, ", ", &code/1)}"))
      ]
      |> Enum.reject(&is_nil/1)

    # Plan EP5b: what the actor answers for, one line each under it.
    responsibilities =
      for r <- Map.get(a, :responsibilities, []),
          do: "\n  - responsibility #{labelled(site, r)}#{source_note(r)}"

    "- #{labelled(site, a)} · #{a.kind}#{Enum.map_join(extra, "", &" · #{&1}")}" <>
      source_note(a) <> Enum.join(responsibilities)
  end

  # When a timer fires, from its declaration (plan N3): its label names what it is for,
  # so the time is the declaration's words, never the label's. P4 holds a timer to
  # exactly one of `wait:` and `at:`.
  defp when_fires(_site, %{wait: wait}) when wait != nil, do: "#{duration(wait)} after it is set"
  defp when_fires(%{audience: :owner}, %{at: _at}), do: "at a moment the run holds"
  defp when_fires(_site, %{at: at}), do: "at #{code(at)}"

  # Where a declaration listed on another's page comes from, after its other facts (plan
  # EP1). A declaration with a page of its own says it under its title instead.
  defp source_note(declaration) do
    case Map.get(declaration, :source) do
      nil -> ""
      source -> " · _source: #{cell(source)}_"
    end
  end

  defp external(site, e) do
    extra =
      [
        if(e.unavailable_looks_like, do: "unavailable looks like: #{e.unavailable_looks_like}"),
        if(e.expected_latency, do: "expected latency #{duration(e.expected_latency)}")
      ]
      |> Enum.reject(&is_nil/1)

    # Plan EP5a: what the system does when an effect calls it, one line each under it.
    operations =
      for o <- Map.get(e, :operations, []),
          do: "\n  - operation #{labelled(site, o)}#{source_note(o)}"

    "- #{labelled(site, e)} · #{e.direction}#{Enum.map_join(extra, "", &" · #{&1}")}" <>
      source_note(e) <> Enum.join(operations)
  end

  defp relation(site, %{between: [_ | _] = between} = r) do
    bullet(
      ["#{relation_type(site, r)} between "] ++
        joined(Enum.map(between, &context_or_external(site, &1))) ++
        [relation_terms(r), source_note(r)]
    )
  end

  defp relation(site, r) do
    bullet([
      "#{relation_type(site, r)}: ",
      context_or_external(site, r.upstream),
      " upstream of ",
      context_or_external(site, r.downstream),
      relation_terms(r),
      source_note(r)
    ])
  end

  defp relation_type(%{audience: :owner}, r),
    do: r.type |> to_string() |> String.replace("_", " ")

  defp relation_type(_site, r), do: r.type

  # Plan EP5b: each pair as the first end's word and the second's.
  defp relation_terms(%{terms: [_ | _] = terms}),
    do: " · terms: " <> Enum.map_join(terms, ", ", fn [a, b] -> ~s|"#{a}" ↔ "#{b}"| end)

  defp relation_terms(_relation), do: ""

  defp context_or_external(site, name) do
    if Enum.any?(site.domain.contexts, &(&1.name == name)),
      do: link(context_name(site, name), context_path(name)),
      else: "#{external_name(site, name)} (external)"
  end

  # --- a value, an entity ------------------------------------------------------------

  defp value_page(site, v) do
    [
      "# Value #{title_name(site, v)}",
      "",
      domain_link(site),
      "",
      facts([
        value_type(site, v),
        code_fact(site, if(v.unit, do: "Unit: #{code(v.unit)}.")),
        if(v.context,
          do: row(["Context: ", link(context_name(site, v.context), context_path(v.context))])
        ),
        if(Map.get(v, :source), do: "_Source: #{v.source}_")
      ]),
      if(v.fields != [], do: fields_section(site, "Fields", v.fields), else: []),
