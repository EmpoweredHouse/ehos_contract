defmodule EhOsContract.Brief do
  @moduledoc """
  One process as a document to put in front of a person: the flow, the events in
  the client's own words, the promises as sentences, and what each event is
  actually for.

  ## Why this is not the conformance report

  `EhOsContract.Report` answers *did the deployed code do what the process says* and needs a
  log. This answers *is this what the process says at all* and needs nothing but
  the contract. Different question, different reader, different moment — before
  anything is built rather than after.

  ## Why it is not the diagram either

  Two rounds of review on a real contract showed the two halves catch different
  mistakes, and neither substitutes for the other:

  | Artifact | Answers | What it caught |
  | --- | --- | --- |
  | the drawing | is this **shape** right | three ordering claims that were missing |
  | the listing | does this element **belong** | six events that were fields on a document |

  So the document carries both, and the listing is not decoration around the
  picture — it is the half that found the larger mistake.

  ## The column that does the work

  For every event the document computes **what depends on it having happened**:
  it ends the process, it opens or satisfies or is the fallback of a promise, a
  handler reacts to it, an external dependency hangs off it.

  **An event with an empty cell is the finding.** That is the test
  `contract-distillation` now applies to every candidate, and having it computed
  here means the artifact checks for the mistake that produced it — the six
  removed from the clinical visit would each have shown an empty cell before
  anybody read the diagram.

  It is a *hint*, not a verdict: an event may be declared ahead of the handler
  that will react to it, which is the ordinary state mid-rollout (notes §5). The
  document says so rather than accusing.

  ## HTML, and why it is the deliverable rather than a step

  These sessions happen on a shared screen, where HTML reflows, can be searched and
  can be copied out of. Anybody who wants paper prints it, and the stylesheet
  carries `@page` rules so that gives A4 with nothing else installed. An earlier
  version printed the file through headless Chrome and that step bought nothing.

  Self-contained: the diagram is inlined as SVG, nothing is fetched, and the file
  opens with no network. Shipping the mermaid source with a script to render it
  would make a document handed to a client depend on the internet to show its own
  picture.
  """

  alias EhOsContract.Registry

  @doc """
  The document for one process of one contract, as a self-contained HTML string.

  `:diagram` takes SVG markup to inline — produced by `mix eh_os_contract.graph --process`
  through `mmdc`. Without it the document is still complete, and says where the
  picture would have been rather than pretending there is none to draw.
  """
  @spec render(module(), atom(), keyword()) :: String.t()
  def render(contract, process_name, opts \\ []) do
    process =
      Enum.find(contract.processes(), &(&1.name == process_name)) ||
        raise ArgumentError, "#{inspect(contract)} declares no process #{inspect(process_name)}"

    events = contract.events_of(process_name)
    traces = Enum.filter(contract.traces(), &(contract.process_of(&1.from).name == process_name))

    """
    <!-- generated by mix eh_os_contract.brief — do not edit, edit the contract -->
    <html lang="pl"><head><meta charset="utf-8">
    <title>#{escape(process.label)}</title>
    <style>#{style()}</style>
    </head><body>
    #{header(contract, process)}
    #{diagram(opts[:diagram])}
    #{events_section(events, traces)}
    #{promises_section(traces, events)}
    #{externals_section(contract, events)}
    #{footer()}
    </body></html>
    """
  end

  defp header(contract, process) do
    """
    <h1>#{escape(process.label)}</h1>
    <p class="meta">#{inspect(contract)} · wersja kontraktu #{contract.version()} ·
    przebieg liczony per #{Enum.map_join(process.instance, ", ", &"<code>#{&1}</code>")}</p>
    <p class="warn"><strong>Wersja robocza.</strong> Wszystko poniżej wyciągnęliśmy
    z warsztatów i niczego jeszcze nie uzgodniliśmy. Prosimy o poprawki — też drobne,
    też takie, które wywracają cały obrazek.</p>
    """
  end

  defp diagram(nil) do
    """
    <h2>Przebieg</h2>
    <p class="warn">Diagramu nie dołączono. Zrób go przez <code>mix eh_os_contract.graph --mermaid
    --process …</code> i <code>mmdc … -o schemat.svg</code>, a potem podaj
    <code>--diagram schemat.svg</code>.</p>
    """
  end

  defp diagram(svg), do: ~s(<h2>Przebieg</h2>\n<figure>#{svg}</figure>)

  defp events_section(events, traces) do
    rows =
      for e <- events do
        depends = depends_on_it(e, traces)
        cls = if depends == [], do: ~s( class="empty"), else: ""

        cell =
          case depends do
            [] -> "<em>nic — sprawdzić, czy to fakt, czy pole na wizycie</em>"
            list -> Enum.join(list, "<br>")
          end

        ~s(<tr#{cls}><td>#{escape(e.label)}</td><td><code>#{e.stage || "—"}</code></td><td>#{cell}</td></tr>)
      end

    """
    <h2>Zdarzenia</h2>
    <p>W prawej kolumnie jest <strong>to, co dzieje się dlatego, że dany fakt zaszedł</strong>.
    Czerwony wiersz znaczy, że nie znaleźliśmy niczego takiego. Zwykle wychodzi wtedy,
    że to nie zdarzenie, tylko pole, które ktoś wypełnia w trakcie wizyty. Czasem znaczy
    tylko tyle, że obsługa jeszcze nie powstała.</p>
    <table><thead><tr><th>Fakt</th><th>Etap</th><th>Co od tego zależy</th></tr></thead>
    <tbody>#{Enum.join(rows, "\n")}</tbody></table>
    """
  end

  # Everything the contract itself says an event is for. Deliberately computed
  # rather than written by hand: a hand-kept column is the first thing to go stale,
  # and this one is the document's whole argument.
  defp depends_on_it(event, traces) do
    handlers =
      for h <- Registry.handlers_for(event.name),
          do: "obsługuje <code>#{inspect(h.module)}</code>"

    roles =
      for t <- traces, role = trace_role(t, event.name), role != nil do
        "#{role} obietnicę <em>#{t.name}</em>"
      end

    terminal = if event.terminal, do: ["kończy proces"], else: []
    external = if event.depends_on, do: ["zależy od <code>#{event.depends_on}</code>"], else: []

    terminal ++ roles ++ handlers ++ external
  end

  defp trace_role(%{from: name}, name), do: "otwiera"
  defp trace_role(%{eventually: name}, name), do: "spełnia"
  defp trace_role(%{or_else: name}, name), do: "zamyka zapasowo"
  defp trace_role(_, _), do: nil

  defp promises_section([], _events) do
    """
    <h2>Obietnice</h2>
    <p>Ten proces nie ma żadnego terminu i nie musi mieć. Sprawdzamy w nim kolejność
    oraz to, które ścieżki nigdy nie zostały przejechane; zegar jest potrzebny tylko tam,
    gdzie ktoś podał liczbę.</p>
    """
  end

  defp promises_section(traces, events) do
    label = fn name ->
      case Enum.find(events, &(&1.name == name)) do
        nil -> to_string(name)
        e -> escape(e.label)
      end
    end

    items =
      for t <- traces do
        window = if t.within, do: " w ciągu #{EhOsContract.Duration.humanize(t.within)}", else: ""
        alt = if t.or_else, do: ", albo <strong>#{label.(t.or_else)}</strong>", else: ""

        ~s(<li>Po <strong>#{label.(t.from)}</strong>#{window} następuje ) <>
          ~s(<strong>#{label.(t.eventually)}</strong>#{alt}.</li>)
      end

    """
    <h2>Obietnice</h2>
    <p>Każde zdanie ma w środku liczbę, więc da się je <strong>poprawić</strong>.
    Zła liczba albo termin liczony od złego momentu dają potem raport, który świeci
    na zielono, kiedy termin został złamany.</p>
    <ol class="promises">#{Enum.join(items, "\n")}</ol>
    """
  end

  defp externals_section(contract, events) do
    names = events |> Enum.map(& &1.depends_on) |> Enum.filter(& &1) |> Enum.uniq()

    case names do
      [] ->
        ""

      _ ->
        rows =
          for n <- names, x = Enum.find(contract.externals(), &(&1.name == n)) do
            ~s(<tr><td>#{escape(x.label)}</td><td>#{escape(x.unavailable_looks_like || "—")}</td></tr>)
          end

        """
        <h2>Zależności poza systemem</h2>
        <p>Kiedy któraś jest niedostępna, <strong>zawieszamy ocenę przebiegu zamiast
        uznawać go za naruszony</strong>. Raport nie powinien mówić Wam, że złamaliście
        własną umowę, kiedy leżał cudzy serwer.</p>
        <table><thead><tr><th>Zależność</th><th>Jak wygląda niedostępność</th></tr></thead>
        <tbody>#{Enum.join(rows, "\n")}</tbody></table>
        """
    end
  end

  defp footer do
    """
    <h2>Czego tu nie ma</h2>
    <p>Nie ma pól, kluczy technicznych ani tego, co system zapisuje o pacjencie; to jest
    materiał dla programisty. Nie ma też niczego o konkretnej wizycie ani osobie, bo ten
    dokument opisuje ścieżki, którymi chodzi proces.</p>
    """
  end

  defp style do
    """
    @page { size: A4; margin: 18mm; }
    body { font: 11pt/1.5 -apple-system, Segoe UI, Roboto, sans-serif; color: #1a1a1a; max-width: 62em; margin: 0 auto; }
    h1 { font-size: 20pt; margin: 0 0 .2em; }
    h2 { font-size: 13pt; margin: 1.8em 0 .5em; border-bottom: 2px solid #e65100; padding-bottom: .2em; }
    .meta { color: #555; font-size: 9pt; margin: 0 0 1em; }
    .warn { background: #fff8e1; border-left: 3px solid #f9a825; padding: .6em .9em; }
    table { border-collapse: collapse; width: 100%; font-size: 10pt; }
    th, td { border: 1px solid #ddd; padding: .45em .6em; text-align: left; vertical-align: top; }
    th { background: #f5f5f5; }
    tr.empty td { background: #ffebee; }
    code { background: #f0f0f0; padding: 0 .25em; border-radius: 2px; font-size: .9em; }
    figure { margin: 0; text-align: center; page-break-inside: avoid; }
    figure svg { max-width: 100%; height: auto; }
    ol.promises li { margin: .5em 0; }
    """
  end

  # The labels are the client's own sentences and may hold anything they wrote.
  defp escape(nil), do: ""

  defp escape(text) do
    text
    |> String.replace("&", "&amp;")
    |> String.replace("<", "&lt;")
    |> String.replace(">", "&gt;")
  end
end
