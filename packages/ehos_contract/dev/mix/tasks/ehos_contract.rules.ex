defmodule Mix.Tasks.EhosContract.Rules do
  @shortdoc "Regenerates docs/rules.md from the rule catalog"

  @moduledoc """
  Writes `docs/rules.md`, the page every finding of `mix ehos_contract.check` links
  to, from `EhosContract.Check.Catalog` — the whole file, one entry per rule, each
  under a heading that is the rule's name, so the name is its anchor.

  `--check` verifies the file is current and exits non-zero otherwise: a page
  describing rules beside the list of rules is a second copy, and a second copy
  drifts. The package's `mix check` runs
  it.
  """

  use Boundary, classify_to: EhosContract
  use Mix.Task

  alias EhosContract.Check.Catalog

  @path "docs/rules.md"

  @impl Mix.Task
  def run(args) do
    :io.setopts(:standard_io, encoding: :unicode)
    {opts, _} = OptionParser.parse!(args, strict: [check: :boolean])

    Mix.Task.run("compile")

    current = if File.exists?(@path), do: File.read!(@path)
    generated = page()

    cond do
      current == generated ->
        Mix.shell().info("#{@path}: current")

      opts[:check] ->
        Mix.raise(
          "#{@path} is out of date with EhosContract.Check.Catalog. Run `mix ehos_contract.rules`."
        )

      true ->
        File.write!(@path, generated)
        Mix.shell().info("#{@path}: regenerated")
    end
  end

  defp page do
    """
    <!-- Generated by `mix ehos_contract.rules` from EhosContract.Check.Catalog. Do not edit. -->

    # The rules of `mix ehos_contract.check`

    `mix ehos_contract.check` reads every contract of the application at once and reports what a
    contract may legally say and a reader should still hear about. Each finding names one of the rules
    below, and the name does not change between versions; the sentence may.

    - An **error** fails the task. A **warning** fails it under `--warnings-as-errors`. A **notice**
      never does. A rule's level is fixed, and nothing silences a rule: a finding goes away when the
      model changes.
    - Where a rule is one of [ESDM](https://www.esdm.io/reference/linter-rules/)'s, it has ESDM's name,
      and its entry says which ESDM rule it follows and how it differs.
    - The rules a contract cannot compile without — `N1`, `X2` and the rest — are the compiler's, not
      this task's, and keep the codes they are printed with.

    """ <> Enum.map_join(Catalog.rules(), "\n", &entry/1)
  end

  defp entry(rule) do
    level = Catalog.level_word(rule.level)
    esdm = if rule.esdm, do: " · ESDM: `#{rule.esdm}`", else: ""

    """
    ## `#{rule.id}`

    **#{level}**#{esdm}

    #{rule.summary}

    #{String.trim_trailing(rule.text)}
    """
  end
end
