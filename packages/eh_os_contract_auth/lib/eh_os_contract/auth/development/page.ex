defmodule EhOsContract.Auth.Development.Page do
  @moduledoc false
  # The HTML of `/dev/sign-in`, for `EhOsContract.Auth.Development.Router`: one form, no
  # script, every value escaped, and at most one link, the host's stylesheet. The browser asks
  # for it, and for what it loads, such as fonts, only after the guard let the page through
  # (#640).
  #
  # The page is drawn by its own rules, written on the design system's tokens (`--surface-1`,
  # `--text-secondary`, …) with a fallback value each. The host's stylesheet, when it imports
  # ehos_design, defines the tokens, the fonts and the body, so the page takes the
  # application's look; without it, the fallbacks give a plain light page. The controls also
  # carry daisyUI's classes (`btn`, `input`, `checkbox`), which an application generated by
  # Phoenix 1.8 has in its stylesheet because its `core_components.ex` uses them. Tailwind's
  # utilities are not used: a host builds them only from the files it names in `@source`,
  # and this one is not among them.
  #
  # Two kinds of rule, by the cascade layer they sit in. The look of the body and of the
  # controls is in the layer `dev-sign-in`, which this `<style>` declares before the host's
  # stylesheet, so it is the lowest layer: the host's base styles and daisyUI's components win
  # over it. A stylesheet with Tailwind's preflight but without these daisyUI classes leaves the
  # controls bare. The page's layout is in no layer, so it wins over the preflight, which resets
  # headings, fieldsets and spacing. Of what daisyUI draws, it sets only the display, width and
  # margin of a text field, on purpose: one field to a line, as wide as its fieldset.

  import Plug.HTML, only: [html_escape: 1]

  @style """
  @layer dev-sign-in{
  body{font:15px/1.5 var(--sans,system-ui,sans-serif);color:var(--text-primary,#1a1a1a);background:var(--canvas,#fff)}
  input[type=text]{font:inherit;padding:.3rem .5rem;border:1px solid var(--border-soft,#ccc);border-radius:var(--radius-md,6px);background:var(--surface-2,#fff);color:inherit}
  button{font:inherit;font-weight:500;padding:.4rem 1rem;border:1px solid var(--border-strong,#999);border-radius:var(--radius-md,6px);background:var(--text-primary,#1a1a1a);color:var(--canvas,#fff);cursor:pointer}
  }
  main{max-width:40rem;margin:0 auto;padding:2rem 1rem}
  h1{font-size:1.4rem;font-weight:500;line-height:1.3;margin:0 0 .75rem}
  main>p{margin:0 0 1rem;color:var(--text-secondary,#444)}
  fieldset{border:1px solid var(--border-soft,#ccc);border-radius:var(--radius-lg,8px);background:var(--surface-1,transparent);margin:0 0 1rem;padding:.5rem 1rem .75rem;min-width:0}
  legend{padding:0 .25rem;color:var(--text-secondary,#444)}
  label{display:block;margin:.5rem 0}
  label>input[type=checkbox]{vertical-align:middle;margin:0 .5rem 0 0}
  label>input[type=text]{display:block;width:100%;box-sizing:border-box;margin-top:.25rem}
  small{display:block;color:var(--text-tertiary,#555);margin-left:1.75rem}
  label>input[type=text]+small{margin:.25rem 0 0}
  .error{background:var(--error-soft,#fde8e8);border:1px solid var(--error-border,#e0a0a0);color:var(--error-ink,inherit);border-radius:var(--radius-md,6px);padding:.5rem 1rem}
  """

  @spec render(keyword()) :: iodata()
  def render(assigns) do
    actors = Keyword.fetch!(assigns, :actors)

    [
      "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">",
      "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">",
      # The address may carry the token: no request of the page sends it as the referrer, even
      # where a plug of the endpoint replaces the router's `referrer-policy` header.
      "<meta name=\"referrer\" content=\"no-referrer\">",
      "<title>Development sign-in</title><style>",
      @style,
      "</style>",
      stylesheet(Keyword.get(assigns, :stylesheet)),
      "</head><body><main><h1>Development sign-in</h1>",
      "<p>Sign in as a person with actors of the domain. The key that signs the credential ",
      "was made when the application started; EHOS did not issue it.</p>",
      error(assigns[:error]),
      "<form method=\"post\" action=\"/dev/sign-in\">",
      hidden("_csrf_token", Keyword.fetch!(assigns, :csrf_token)),
      hidden("return_to", Keyword.fetch!(assigns, :return_to)),
      "<fieldset><legend>Person</legend><label>Subject ",
      "<input class=\"input\" type=\"text\" name=\"subject\" placeholder=\"dev\" value=\"",
      escape(assigns[:subject] || ""),
      "\"></label></fieldset>",
      actors(actors, Keyword.get(assigns, :chosen, [])),
      scopes(actors, Keyword.get(assigns, :scopes, %{})),
      "<button class=\"btn btn-primary\" type=\"submit\">Sign in</button></form></main></body></html>"
    ]
  end

  # After the page's own `<style>`, so that its layer is declared first and is the lowest.
  defp stylesheet(nil), do: []
  defp stylesheet(path), do: ["<link rel=\"stylesheet\" href=\"", escape(path), "\">"]

  defp error(nil), do: []
  defp error(message), do: ["<p class=\"error\" role=\"alert\">", escape(message), "</p>"]

  defp actors([], _chosen),
    do: "<p>The contracts grant no actor a capability, so there is nobody to sign in as.</p>"

  defp actors(actors, chosen) do
    [
      "<fieldset><legend>Actors</legend>",
      for actor <- actors do
        [
          "<label><input class=\"checkbox checkbox-sm\" type=\"checkbox\" name=\"actors[]\" value=\"",
          escape(actor.role),
          "\"",
          if(actor.role in chosen, do: " checked", else: ""),
          ">",
          escape(actor.role),
          "<small>",
          escape(Enum.join(actor.capabilities, ", ")),
          "</small></label>"
        ]
      end,
      "</fieldset>"
    ]
  end

  defp scopes(actors, values) do
    case actors |> Enum.flat_map(& &1.scopes) |> Enum.uniq() |> Enum.sort() do
      [] ->
        []

      scopes ->
        [
          "<fieldset><legend>Scopes</legend>",
          for scope <- scopes do
            needed_by = for actor <- actors, scope in actor.scopes, do: actor.role

            [
              "<label>",
              escape(scope),
              " <input class=\"input\" type=\"text\" name=\"scopes[",
              escape(scope),
              "]\" value=\"",
              escape(Map.get(values, scope, "")),
              "\"><small>for ",
              escape(Enum.join(needed_by, ", ")),
              "</small></label>"
            ]
          end,
          "</fieldset>"
        ]
    end
  end

  defp hidden(name, value),
    do: ["<input type=\"hidden\" name=\"", name, "\" value=\"", escape(value), "\">"]

  defp escape(value), do: html_escape(to_string(value))
end
